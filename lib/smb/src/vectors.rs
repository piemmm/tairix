//! Microsoft's published SMB 3 test vectors, captured between Windows clients
//! and servers and printed in two posts on the Microsoft Open Specifications
//! blog: *Encryption in SMB 3.0: A protocol perspective* (2012) and *SMB 3.1.1
//! Encryption in Windows 10* (2015). The hex is as published.

use alloc::vec::Vec;

use crate::header::HEADER_LEN;
use crate::negotiate::{Cipher, Dialect};
use crate::wire::Encoder;

/// `hex` as bytes.
pub fn bytes(hex: &str) -> Vec<u8> {
    assert!(hex.len().is_multiple_of(2), "an odd number of hex digits");
    (0..hex.len())
        .step_by(2)
        .map(|at| u8::from_str_radix(&hex[at..at + 2], 16).expect("hex"))
        .collect()
}

/// `hex` as an array.
pub fn array<const N: usize>(hex: &str) -> [u8; N] {
    bytes(hex).try_into().expect("the array's length")
}

/// What `encode` writes behind a stand-in header: a decoded message's body
/// re-encoded, to hold against the bytes it was decoded from.
pub fn reencoded(encode: impl FnOnce(&mut Encoder)) -> Vec<u8> {
    let mut enc = Encoder::new();
    enc.zeros(HEADER_LEN);
    encode(&mut enc);
    enc.finish().expect("encodes")
}

/// One request and its response, each as sent and as sealed.
pub struct Exchange {
    pub request: &'static str,
    pub sealed_request: &'static str,
    pub sealed_response: &'static str,
    pub response: &'static str,
}

/// One captured session: its keys, and a `WRITE` and a `READ` Windows sealed
/// under them.
pub struct Capture {
    pub dialect: Dialect,
    pub cipher: Cipher,
    pub session_id: u64,
    pub session_key: &'static str,
    /// The pre-auth integrity hash the keys bind; empty for 3.0.
    pub preauth: &'static str,
    pub signing_key: &'static str,
    pub client_to_server: &'static str,
    pub server_to_client: &'static str,
    pub application_key: &'static str,
    pub write: Exchange,
    pub read: Exchange,
}

