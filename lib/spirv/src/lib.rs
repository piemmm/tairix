//! SPIR-V shader modules: the checked model the validator, the builder and
//! the GPU backends share, its total and bounded decoder, and its encoder
//! (`plans/SHADER.md` SH1).
//!
//! # What the decoder guarantees
//!
//! [`Module::decode`] takes a module in either byte order and either refuses
//! it, naming the word at fault, or answers a [`Module`] in which:
//!
//! - every instruction's opcode is one the grammar recognises, and its words
//!   hold exactly the operands the grammar gives it;
//! - every id is nonzero and below the module's bound, and no id is defined
//!   twice;
//! - every enumerated operand is a value its kind has, followed by the
//!   parameters that value takes;
//! - every string is terminated, zero-padded and UTF-8;
//! - every literal whose width is its context's — a constant's, a switch
//!   case's — is as wide as the numeric type defined before it;
//! - every extended instruction names an imported, recognised set, an
//!   instruction of that set, and that instruction's operands.
//!
//! It is total: no input panics it, and it allocates in proportion to the
//! input's length and nothing an input value chose. A module past
//! [`MAX_MODULE_BYTES`] or [`MAX_INSTRUCTIONS`] is refused.
//!
//! # The grammar
//!
//! `src/tables.rs` is generated by `cargo xtask spirv` from the Khronos
//! machine-readable grammar vendored in `assets/`. It recognises the core and
//! what the Khronos multi-vendor extensions add; an instruction or value that
//! is provisional, that only one vendor's extension enables, or whose every
//! capability is itself unrecognised is refused as unknown. Of extended
//! instruction sets it recognises `GLSL.std.450`.
//!
//! What a module means — its types, control flow, capabilities and bindings —
//! is the validator's to judge, not the decoder's.

