/// The count1 region's two trees: quadruples coded, or four plain bits.
const COUNT1_TREES: [u8; 2] = [15, 16];

/// Bits a lookup's first level indexes; longer codes continue in levels of
/// at most [`SUB_BITS`].
const ROOT_BITS: u8 = 8;
const SUB_BITS: u8 = 5;

const LEAF_VALUE: u16 = 0x00FF;
const POINTER: u16 = 0x8000;
const OFFSET_MASK: u16 = 0x07FF;

/// Every tree's lookup, built once: an entry is a leaf — the value and the
/// bits its code takes at that level — or the start and width of the next
/// level.
pub(super) struct Lookups {
    entries: Vec<u16>,
    /// Where each tree's lookup starts, and its first level's width.
    roots: [(u16, u8); 17],
}

impl Lookups {
    /// Build every tree's lookup.
    ///
    /// # Errors
    ///
    /// [`DecodeError::OutOfMemory`] when the lookups cannot be allocated.
    pub(super) fn build() -> Result<Self, DecodeError> {
        let mut entries = Vec::new();
        let mut roots = [(0, 0); 17];
        for (tree, root) in TREES.iter().zip(&mut roots) {
            let start = entries.len();
            let width = tree
                .codes
                .iter()
                .map(|code| code.len)
                .fold(0, u8::max)
                .min(ROOT_BITS);
            let mut codes = Vec::new();
            codes
                .try_reserve_exact(tree.codes.len())
                .map_err(|_| DecodeError::OutOfMemory)?;
            codes.extend(
                tree.codes
                    .iter()
                    .zip(0..=u8::MAX)
                    .map(|(code, at)| (*code, value_of(at, tree.ylen))),
            );
            level(&mut entries, start, &codes, width)?;
            *root = (
                u16::try_from(start).map_err(|_| DecodeError::OutOfMemory)?,
                width,
            );
        }
        Ok(Self { entries, roots })
    }

    /// The pair `(x, y)` the next big-values code of `table_select` stands
    /// for, escapes and signs read: `None` for a table that codes nothing.
    pub(super) fn pair(
        &self,
        bits: &mut BitReader<'_>,
        table_select: u8,
    ) -> Result<Option<(i32, i32)>, Exhausted> {
        let Some(&Some((tree, linbits))) = BIG_VALUES.get(usize::from(table_select)) else {
            return Ok(None);
        };
        let value = self.decode(bits, tree)?;
        let x = signed(bits, u32::from(value >> 4), linbits)?;
        let y = signed(bits, u32::from(value & 0xF), linbits)?;
        Ok(Some((x, y)))
    }

    /// The next count1 code in tree `table` (0 or 1): the quadruple's
    /// magnitudes `v w x y`, most significant first, each a bit. Their signs
    /// follow, read by [`count1_signs`].
    pub(super) fn count1(&self, bits: &mut BitReader<'_>, table: bool) -> Result<u8, Exhausted> {
        self.decode(bits, COUNT1_TREES[usize::from(table)])
    }

    /// The value the next code of tree `tree` stands for.
    fn decode(&self, bits: &mut BitReader<'_>, tree: u8) -> Result<u8, Exhausted> {
        let (start, mut width) = self.roots[usize::from(tree)];
        let mut base = usize::from(start);
        loop {
            let entry = self.entries[base + bits.peek(u32::from(width)) as usize];
            if entry & POINTER == 0 {
                bits.skip(u32::from(entry >> 8))?;
                return Ok((entry & LEAF_VALUE) as u8);
            }
            bits.skip(u32::from(width))?;
            width = ((entry >> 11) & 0xF) as u8;
            base = usize::from(start) + usize::from(entry & OFFSET_MASK);
        }
    }
}

/// The value at `at` in a tree of `ylen` columns: `x << 4 | y`, or the
/// quadruple's four bits.
fn value_of(at: u8, ylen: u8) -> u8 {
    if ylen == 0 {
        return at;
    }
    ((at / ylen) << 4) | (at % ylen)
}

/// Lay one level of `width` bits for `codes` — each relative to this level's
/// start — at the end of `entries`, and every level beneath it after it.
fn level(
    entries: &mut Vec<u16>,
    tree_start: usize,
    codes: &[(Code, u8)],
    width: u8,
) -> Result<(), DecodeError> {
    let base = entries.len();
    let slots = 1usize << width;
    entries
        .try_reserve(slots)
        .map_err(|_| DecodeError::OutOfMemory)?;
    entries.resize(base + slots, 0);
    for &(code, value) in codes.iter().filter(|(code, _)| code.len <= width) {
        let shift = width - code.len;
        let first = base + ((code.bits as usize) << shift);
        entries[first..first + (1 << shift)].fill(u16::from(code.len) << 8 | u16::from(value));
    }
    for prefix in 0..1u32 << width {
        let continues = |code: &Code| code.len > width && code.bits >> (code.len - width) == prefix;
        if !codes.iter().any(|(code, _)| continues(code)) {
            continue;
        }
        let mut group = Vec::new();
        group
            .try_reserve_exact(codes.len())
            .map_err(|_| DecodeError::OutOfMemory)?;
        group.extend(
            codes
                .iter()
                .filter(|(code, _)| continues(code))
                .map(|&(code, value)| {
                    let rest = code.len - width;
                    (c(rest, code.bits & ((1 << rest) - 1)), value)
                }),
        );
        let sub = group
            .iter()
            .map(|(code, _)| code.len)
            .fold(0, u8::max)
            .min(SUB_BITS);
        let offset = u16::try_from(entries.len() - tree_start)
            .ok()
            .filter(|offset| *offset <= OFFSET_MASK)
            .ok_or(DecodeError::OutOfMemory)?;
        entries[base + prefix as usize] = POINTER | u16::from(sub) << 11 | offset;
        level(entries, tree_start, &group, sub)?;
    }
    Ok(())
}

/// The quadruple a count1 code's magnitudes `code` make, each non-zero one
/// signed by the next bit; a sign past the stream's bits reads as positive.
pub(super) fn count1_signs(bits: &mut BitReader<'_>, code: u8) -> [i32; 4] {
    core::array::from_fn(|at| {
        if code >> (3 - at) & 1 == 0 {
            return 0;
        }
        if bits.read(1) == Ok(1) {
            -1
        } else {
            1
        }
    })
}

/// A magnitude `magnitude` as coded — escaped past 15 by `linbits` more bits
/// — then its sign, where it is non-zero.
fn signed(bits: &mut BitReader<'_>, magnitude: u32, linbits: u8) -> Result<i32, Exhausted> {
    let mut magnitude = magnitude;
    if magnitude == 15 && linbits > 0 {
        magnitude += bits.read(u32::from(linbits))?;
    }
    if magnitude == 0 {
        return Ok(0);
    }
    // At most 15 and thirteen linbits, far inside `i32`.
    let value = magnitude.cast_signed();
    Ok(if bits.read(1)? == 1 { -value } else { value })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every table is a complete prefix code over exactly the values it
    /// stands for, so no bit string decodes to two values or to none.
    #[test]
    fn every_table_is_a_complete_prefix_code() {
        for tree in &TREES {
            let kraft: u64 = tree
                .codes
                .iter()
                .map(|code| 1u64 << (32 - u32::from(code.len)))
                .sum();
            assert_eq!(kraft, 1 << 32, "{} codes", tree.codes.len());
            for (at, a) in tree.codes.iter().enumerate() {
                for b in &tree.codes[at + 1..] {
                    let (short, long) = if a.len <= b.len { (a, b) } else { (b, a) };
                    assert_ne!(
                        long.bits >> (long.len - short.len),
                        short.bits,
                        "a code prefixes another"
                    );
                }
            }
        }
    }

    /// Each code, laid alone into a stream, decodes to the value it stands
    /// for and consumes exactly its own bits.
    #[test]
    fn every_code_decodes_to_its_own_value() {
        let lookups = Lookups::build().expect("built");
        for (tree, layout) in (0u8..).zip(&TREES) {
            for (code, at) in layout.codes.iter().zip(0..=u8::MAX) {
                let word = (u64::from(code.bits) << (64 - u32::from(code.len))) | 1 << 20;
                let bytes = word.to_be_bytes();
                let mut bits = BitReader::new(&bytes);
                let value = lookups.decode(&mut bits, tree).expect("decodes");
                assert_eq!(value, value_of(at, layout.ylen), "tree {tree} value {at}");
                assert_eq!(bits.bits_consumed(), usize::from(code.len));
            }
        }
    }

    #[test]
    fn an_escape_takes_its_linbits_and_a_sign_follows_any_non_zero_value() {
        let lookups = Lookups::build().expect("built");
        // Table 16, x = 15 escaped by one linbit, y = 0: the code for (15, 0),
        // the linbit 1, then x's sign 1.
        let code = H16[15 * 16];
        let word = (u64::from(code.bits) << 2 | 0b11) << (62 - u32::from(code.len));
        let bytes = word.to_be_bytes();
        let mut bits = BitReader::new(&bytes);
        assert_eq!(lookups.pair(&mut bits, 16), Ok(Some((-16, 0))));
        assert_eq!(lookups.pair(&mut BitReader::new(&[0]), 0), Ok(None));
    }
}
