//! The boot-protocol layouts (USB HID 1.11 Appendix B), as report descriptors
//! the model parses like any other, so a device driven in boot protocol is
//! decoded by the same decoders as one in report protocol.

use crate::descriptor::{DescriptorError, ReportDescriptor};

/// The boot keyboard (HID 1.11 Appendix E.6): eight modifier bits, a reserved
/// byte, six key slots; five LED bits out.
const KEYBOARD: [u8; 63] = [
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02, 0x95, 0x01, 0x75, 0x08, 0x81, 0x01, 0x95, 0x05, 0x75, 0x01,
    0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x91, 0x02, 0x95, 0x01, 0x75, 0x03, 0x91, 0x01, 0x95, 0x06,
    0x75, 0x08, 0x15, 0x00, 0x25, 0x65, 0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, 0xC0,
];

/// The boot mouse (HID 1.11 Appendix E.10) with the wheel byte nearly every
/// boot mouse sends after Y: three button bits, X, Y, wheel.
const MOUSE: [u8; 52] = [
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x01,
    0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03,
    0x81, 0x06, 0xC0, 0xC0,
];

/// The boot keyboard's layout.
///
/// # Errors
///
/// Only the parser's, which a fixed descriptor never meets.
pub fn keyboard() -> Result<ReportDescriptor, DescriptorError> {
    ReportDescriptor::parse(&KEYBOARD)
}

/// The boot mouse's layout.
///
/// # Errors
///
/// Only the parser's, which a fixed descriptor never meets.
pub fn mouse() -> Result<ReportDescriptor, DescriptorError> {
    ReportDescriptor::parse(&MOUSE)
}
