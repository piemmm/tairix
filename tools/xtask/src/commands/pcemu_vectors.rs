//! `cargo xtask pcemu-vectors --import <dir>`: the CPU conformance vectors.
//!
//! `PCEmulator`'s CPU is tested against instructions executed on physical
//! processors: the `SingleStepTests` 8088, 8086 and V20 suites (MIT). They
//! are hundreds of megabytes, so the tree keeps a vetted subset — the first
//! [`PER_GROUP`] vectors of every upstream file, without bus traces — in the
//! compact format `tairix_pcemu::vectors` defines, with a provenance record.
//!
//! Developer-run only, never in CI: `<dir>` holds a local copy of each
//! suite, `<dir>/<cpu>/` with its `*.MOO.gz` files, its `metadata.json` and a
//! `COMMIT` file naming the upstream revision it was taken from. Builds stay
//! offline; the committed subset is reviewed like any other change.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use tairix_pcemu::vectors::{self, Group, Status, Suite, Vector, REGISTERS};

use super::json::{self, Json};
use crate::Context;

/// Where the subsets are committed.
const OUT_DIR: &str = "userland/apps/pcemu/assets/cpu-vectors";

/// Vectors kept from each upstream file.
const PER_GROUP: usize = 32;

/// The ceiling on one upstream file's decompressed size.
const MAX_MOO_BYTES: usize = 512 << 20;

struct Upstream {
    cpu: &'static str,
    repo: &'static str,
}

const SUITES: [Upstream; 3] = [
    Upstream {
        cpu: "8088",
        repo: "https://github.com/SingleStepTests/8088",
    },
    Upstream {
        cpu: "8086",
        repo: "https://github.com/SingleStepTests/8086",
    },
    Upstream {
        cpu: "v20",
        repo: "https://github.com/SingleStepTests/v20",
    },
];

pub fn run(ctx: &Context, args: &[std::ffi::OsString]) -> Result<(), String> {
    let source = match args {
        [flag, dir] if flag == "--import" => PathBuf::from(dir),
        _ => {
            return Err(
                "pcemu-vectors: usage: cargo xtask pcemu-vectors --import <dir>".to_string(),
            )
        }
    };
    let out = ctx.workspace_root.join(OUT_DIR);
    std::fs::create_dir_all(&out)
        .map_err(|e| format!("pcemu-vectors: cannot create {}: {e}", out.display()))?;
    let mut provenance = String::from(
        "# CPU conformance vectors\n\n\
         Generated by `cargo xtask pcemu-vectors --import`; never edit by hand.\n\n\
         Source: the `SingleStepTests` suites, instructions executed on physical\n\
         processors, under the MIT licence in `LICENSE` beside this file. Each\n\
         `<cpu>.pcv` keeps the first 32 vectors of every upstream file, in file\n\
         order, without bus traces: a 32-bit little-endian length, then the\n\
         zlib-compressed `tairix_pcemu::vectors` encoding.\n\n\
         | Suite | Upstream | Commit | Groups | Vectors |\n|---|---|---|---|---|\n",
    );
    let mut digests = String::new();
    for upstream in &SUITES {
        let dir = source.join(upstream.cpu);
        let commit = std::fs::read_to_string(dir.join("COMMIT"))
            .map_err(|e| format!("pcemu-vectors: {}: no COMMIT file: {e}", dir.display()))?;
        let commit = commit.trim().to_string();
        let (suite, files) = import_suite(upstream, &dir)?;
        let encoded =
            vectors::encode(&suite).map_err(|e| format!("pcemu-vectors: {}: {e}", upstream.cpu))?;
        let packed = pack(&encoded)?;
        let file = out.join(format!("{}.pcv", upstream.cpu));
        std::fs::write(&file, &packed)
            .map_err(|e| format!("pcemu-vectors: cannot write {}: {e}", file.display()))?;
        let total: usize = suite.groups.iter().map(|g| g.vectors.len()).sum();
        let _ = writeln!(
            provenance,
            "| `{}` | {} | `{commit}` | {} | {total} |",
            upstream.cpu,
            upstream.repo,
            suite.groups.len()
        );
        let _ = writeln!(
            digests,
            "\n## `{}` upstream files (SHA-256)\n",
            upstream.cpu
        );
        for (name, digest) in files {
            let _ = writeln!(digests, "- `{name}` `{digest}`");
        }
        noteln!(
            "xtask: [pcemu-vectors] {} — {} groups, {total} vectors",
            upstream.cpu,
            suite.groups.len()
        );
    }
    provenance.push_str(&digests);
    let licence = source.join(SUITES[0].cpu).join("LICENSE");
    let licence = std::fs::read(&licence)
        .map_err(|e| format!("pcemu-vectors: {}: {e}", licence.display()))?;
    std::fs::write(out.join("LICENSE"), licence)
        .map_err(|e| format!("pcemu-vectors: LICENSE: {e}"))?;
    std::fs::write(out.join("PROVENANCE.md"), provenance)
        .map_err(|e| format!("pcemu-vectors: PROVENANCE.md: {e}"))
}

/// One upstream suite, and each source file's name and digest.
fn import_suite(upstream: &Upstream, dir: &Path) -> Result<(Suite, Vec<(String, String)>), String> {
    let metadata = std::fs::read_to_string(dir.join("metadata.json"))
        .map_err(|e| format!("pcemu-vectors: {}: metadata.json: {e}", dir.display()))?;
    let metadata =
        json::parse(&metadata).map_err(|e| format!("pcemu-vectors: metadata.json: {e}"))?;
    let opcodes = metadata
        .get("opcodes")
        .ok_or("pcemu-vectors: metadata has no opcodes")?;
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .map_err(|e| format!("pcemu-vectors: {}: {e}", dir.display()))?
        .filter_map(Result::ok)
        .filter_map(|entry| {
            entry
                .file_name()
                .to_str()
                .and_then(|n| n.strip_suffix(".MOO.gz"))
                .map(String::from)
        })
        .collect();
    names.sort();
    let mut groups = Vec::with_capacity(names.len());
    let mut files = Vec::with_capacity(names.len());
    for name in names {
        let path = dir.join(format!("{name}.MOO.gz"));
        let gz =
            std::fs::read(&path).map_err(|e| format!("pcemu-vectors: {}: {e}", path.display()))?;
        files.push((format!("{name}.MOO.gz"), hex(&tairix_crypto::sha256(&gz))));
        let moo = gunzip(&gz).map_err(|e| format!("pcemu-vectors: {}: {e}", path.display()))?;
        let vectors = parse_moo(&moo, PER_GROUP)
            .map_err(|e| format!("pcemu-vectors: {}: {e}", path.display()))?;
        let (status, flags_mask) = classify(opcodes, &name)?;
        groups.push(Group {
            name,
            status,
            flags_mask,
            vectors,
        });
    }
    Ok((
        Suite {
            cpu: upstream.cpu.to_string(),
            groups,
        },
        files,
    ))
}

/// The status and undefined-flags mask the metadata gives a file stem.
fn classify(opcodes: &Json, stem: &str) -> Result<(Status, u16), String> {
    let (opcode, reg) = match stem.split_once('.') {
        Some((op, reg)) => (op, Some(reg)),
        None => (stem.get(..2).unwrap_or(stem), None),
    };
    let entry = opcodes
        .get(opcode)
        .ok_or_else(|| format!("pcemu-vectors: no metadata for {stem}"))?;
    // A file that mixes every ModRM `reg` value is classed by field 0, the
    // documented form.
    let entry = match (reg, entry.get("status")) {
        (Some(reg), _) => entry.get("reg").and_then(|r| r.get(reg)),
        (None, Some(_)) => Some(entry),
        (None, None) => entry.get("reg").and_then(|r| r.get("0")),
    }
    .ok_or_else(|| format!("pcemu-vectors: no metadata for {stem}"))?;
    let status = entry
        .get("status")
        .and_then(Json::as_str)
        .and_then(Status::from_name)
        .ok_or_else(|| format!("pcemu-vectors: {stem}: unknown status"))?;
    let mask = match entry.get("flags-mask") {
        Some(m) => m
            .as_u64()
            .and_then(|m| u16::try_from(m).ok())
            .ok_or_else(|| format!("pcemu-vectors: {stem}: bad flags-mask"))?,
        None => 0xFFFF,
    };
    Ok((status, mask))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::new(), |mut s, b| {
        let _ = write!(s, "{b:02x}");
        s
    })
}

/// A 32-bit length, then the zlib stream.
fn pack(suite: &[u8]) -> Result<Vec<u8>, String> {
    let mut zlib = tairix_compress::zlib::Encoder::new();
    let mut out = vec![0u8; 4 + zlib.bound(suite.len())];
    let length = u32::try_from(suite.len()).map_err(|_| "pcemu-vectors: suite over 4 GiB")?;
    out[..4].copy_from_slice(&length.to_le_bytes());
    let written = zlib
        .compress(
            suite,
            &mut out[4..],
            tairix_compress::deflate::Flush::Finish,
        )
        .map_err(|e| format!("pcemu-vectors: compress: {e}"))?;
    out.truncate(4 + written);
    Ok(out)
}

/// One RFC 1952 member: header, DEFLATE body, CRC-32 and length checked.
fn gunzip(gz: &[u8]) -> Result<Vec<u8>, String> {
    let byte = |at: usize| {
        gz.get(at)
            .copied()
            .ok_or_else(|| "truncated header".to_string())
    };
    if gz.len() < 18 || byte(0)? != 0x1F || byte(1)? != 0x8B || byte(2)? != 8 {
        return Err("not a gzip member".to_string());
    }
    let flags = byte(3)?;
    let mut at = 10usize;
    if flags & 0x04 != 0 {
        at += 2 + usize::from(u16::from_le_bytes([byte(at)?, byte(at + 1)?]));
    }
    for name_or_comment in [0x08u8, 0x10] {
        if flags & name_or_comment != 0 {
            let end = gz
                .get(at..)
                .and_then(|rest| rest.iter().position(|&b| b == 0))
                .ok_or("unterminated header field")?;
            at += end + 1;
        }
    }
    if flags & 0x02 != 0 {
        at += 2;
    }
    let trailer = gz.len() - 8;
    let crc = le32(gz, trailer)?;
    let size = usize::try_from(le32(gz, trailer + 4)?).map_err(|_| "size overflows")?;
    if size > MAX_MOO_BYTES {
        return Err(format!(
            "decompresses to {size} bytes, over the {MAX_MOO_BYTES}-byte ceiling"
        ));
    }
    let mut out = vec![0u8; size];
    let body = gz.get(at..trailer).ok_or("truncated body")?;
    let written = tairix_compress::inflate::inflate_into(body, &mut out)
        .map_err(|e| format!("inflate: {e}"))?;
    if written != size || tairix_crc32::checksum(&out) != crc {
        return Err("CRC-32 or length mismatch".to_string());
    }
    Ok(out)
}

/// The chunk at `at`: its four-byte type and payload.
fn chunk(buf: &[u8], at: usize) -> Option<([u8; 4], &[u8], usize)> {
    let head = buf.get(at..at + 8)?;
    let kind = [head[0], head[1], head[2], head[3]];
    let len = usize::try_from(u32::from_le_bytes([head[4], head[5], head[6], head[7]])).ok()?;
    let body = buf.get(at + 8..at + 8 + len)?;
    Some((kind, body, at + 8 + len))
}

fn chunks(buf: &[u8]) -> impl Iterator<Item = ([u8; 4], &[u8])> {
    let mut at = 0;
    std::iter::from_fn(move || {
        let (kind, body, next) = chunk(buf, at)?;
        at = next;
        Some((kind, body))
    })
}

fn le32(b: &[u8], at: usize) -> Result<u32, String> {
    b.get(at..at + 4)
        .map(|s| u32::from_le_bytes([s[0], s[1], s[2], s[3]]))
        .ok_or_else(|| "short field".to_string())
}

fn counted(b: &[u8]) -> Result<Vec<u8>, String> {
    let n = usize::try_from(le32(b, 0)?).map_err(|_| "length overflows")?;
    b.get(4..4 + n)
        .map(<[u8]>::to_vec)
        .ok_or_else(|| "short run".to_string())
}

/// One captured state: the registers the upstream mask names, the RAM and
/// the queue.
struct State {
    regs: [Option<u16>; REGISTERS],
    ram: Vec<(u32, u8)>,
    queue: Vec<u8>,
}

/// A state's registers (by the upstream mask), RAM and queue.
fn state(body: &[u8]) -> Result<State, String> {
    let mut regs = [None; REGISTERS];
    let mut ram = Vec::new();
    let mut queue = Vec::new();
    for (kind, sub) in chunks(body) {
        match &kind {
            b"REGS" => {
                let mask = u16::from_le_bytes([
                    *sub.first().ok_or("short REGS")?,
                    *sub.get(1).ok_or("short REGS")?,
                ]);
                let mut at = 2;
                for (i, slot) in regs.iter_mut().enumerate() {
                    if mask & (1 << i) != 0 {
                        let v = sub.get(at..at + 2).ok_or("short REGS")?;
                        *slot = Some(u16::from_le_bytes([v[0], v[1]]));
                        at += 2;
                    }
                }
            }
            b"RAM " => {
                let n = usize::try_from(le32(sub, 0)?).map_err(|_| "count overflows")?;
                for i in 0..n {
                    let at = 4 + 5 * i;
                    ram.push((le32(sub, at)?, *sub.get(at + 4).ok_or("short RAM")?));
                }
            }
            b"QUEU" => queue = counted(sub)?,
            _ => {}
        }
    }
    Ok(State { regs, ram, queue })
}

/// The first `keep` tests of a MOO file.
fn parse_moo(moo: &[u8], keep: usize) -> Result<Vec<Vector>, String> {
    let mut out = Vec::with_capacity(keep);
    let mut top = chunks(moo);
    match top.next() {
        Some((kind, _)) if &kind == b"MOO " => {}
        _ => return Err("no MOO header".to_string()),
    }
    for (kind, body) in top {
        if &kind != b"TEST" {
            continue;
        }
        let mut bytes = Vec::new();
        let mut init = None;
        let mut fin = None;
        let mut cycles = 0u16;
        for (sub, payload) in chunks(body.get(4..).ok_or("short TEST")?) {
            match &sub {
                b"BYTS" => bytes = counted(payload)?,
                b"INIT" => init = Some(state(payload)?),
                b"FINA" => fin = Some(state(payload)?),
                b"CYCL" => {
                    cycles =
                        u16::try_from(le32(payload, 0)?).map_err(|_| "cycle count over 65535")?;
                }
                _ => {}
            }
        }
        let init = init.ok_or("TEST without INIT")?;
        let fin = fin.ok_or("TEST without FINA")?;
        let mut regs = [0u16; REGISTERS];
        for (slot, value) in regs.iter_mut().zip(init.regs) {
            *slot = value.ok_or("INIT lacks a register")?;
        }
        out.push(Vector {
            bytes,
            regs,
            queue: init.queue,
            ram: init.ram,
            final_regs: fin.regs,
            final_ram: fin.ram,
            cycles,
        });
        if out.len() == keep {
            break;
        }
    }
    Ok(out)
}
