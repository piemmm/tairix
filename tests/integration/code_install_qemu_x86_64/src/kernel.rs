//! The freestanding x86_64 test kernel: prove code installation end to end
//! on the QEMU x86_64 machine (`plans/PCEMU.md` PC17; `plans/BROWSER.md` BR26).
//!
//! Every syscall and every user fault runs the production
//! `KernelDispatchHook` / `KernelSyscallHandlers` path, over the production
//! `LiveMemMap` producer, a real `KernelProcessWait` and a real
//! `KernelProcessSignal`. The parent role of the fixture
//! (`tests/integration/code_install_program`) is spawned through the
//! production `InitSpawnCtx::spawn_driver_process` seam holding
//! `CAP_JIT_MAP_EXEC`; it starts its workers through the production `spawn`,
//! sandboxed but for one, and drives `code_install` against them: functions a
//! compiler wrote run in the target, the compiler keeps none of the pages it
//! handed over, a compiler serves one target, an unsandboxed child takes no
//! part, and the target releases its code with `mem_unmap`. On this port
//! instruction fetch is coherent with the data side, so an install owes no
//! fence.
//!
//! The chassis reaps the parent through the wait producer's non-blocking poll
//! and PASSes only on a parent exit of 0.

