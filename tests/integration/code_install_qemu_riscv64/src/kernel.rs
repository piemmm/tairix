/// Physical frames the production spawn producer draws from: the parent and
/// its four workers (image, eagerly committed stack top, page tables, and the
/// `tairix-rt` heap each), with the pages the compiler writes. Sized with
/// generous headroom (16 MiB).
const FRAME_COUNT: usize = 4096;

/// Cooperative-loop watchdog: maximum `step` iterations before the test
/// declares the workload deadlocked. Sized generously for QEMU TCG.
const MAX_STEPS: u64 = 5_000_000;

/// Stable audit-event ids for the QEMU transcript.
const TEST_START: EventId = EventId(4570);
const TEST_SPAWNED: EventId = EventId(4571);
const TEST_PASS: EventId = EventId(4572);

/// Failure finisher codes, distinct per failure site.
const FAIL_ZERO_FREQ: NonZeroU16 = fail_point!(1);
const FAIL_FDT: NonZeroU16 = fail_point!(2);
const FAIL_UNEXPECTED_HART: NonZeroU16 = fail_point!(3);
const FAIL_FRAMES: NonZeroU16 = fail_point!(4);
const FAIL_SCHED_NEW: NonZeroU16 = fail_point!(5);
const FAIL_SPAWN: NonZeroU16 = fail_point!(6);
const FAIL_DEADLOCK: NonZeroU16 = fail_point!(7);
const FAIL_NO_DISPATCH: NonZeroU16 = fail_point!(8);
const FAIL_HOOK_INSTALL: NonZeroU16 = fail_point!(9);
const FAIL_RESOLVER_INSTALL: NonZeroU16 = fail_point!(10);
const FAIL_BIAS: NonZeroU16 = fail_point!(11);
const FAIL_POLL: NonZeroU16 = fail_point!(12);
const FAIL_DRAINED: NonZeroU16 = fail_point!(13);
const FAIL_PARENT_STOPPED: NonZeroU16 = fail_point!(14);
const FAIL_PAGING: NonZeroU16 = fail_point!(15);
/// The random reserve could not be seeded.
const FAIL_SEED: NonZeroU16 = fail_point!(16);
/// Base finisher for a non-zero parent exit; the parent's diagnostic exit
/// code is added so the failing role/site is identifiable in the finisher.
const FAIL_EXIT_BASE: NonZeroU16 = fail_point!(100);

/// The test's heap, in bytes.
const HEAP_SIZE: usize = 2 * 1024 * 1024;

/// The global allocator's arena.
static HEAP: Arena<HEAP_SIZE> = Arena::ZERO;

/// Global allocator backed by [`HEAP`].
///
/// SAFETY: the page-aligned `HEAP` static outlives the binary and the
/// allocator is its only consumer.
#[global_allocator]
static ALLOCATOR: FreeListAllocator =
    unsafe { FreeListAllocator::new(HEAP.as_mut_ptr(), HEAP_SIZE) };

/// Identity-mapped physical-frame backing store the live [`FrameAllocator`]
/// serves the spawn producer and the demand-fault path from; inside
/// the 4 GiB identity window the producer's Sv39 page-table walk requires
/// (the `virt` board's RAM base at 2 GiB sits within it).
static FRAME_POOL: Arena<{ PAGE_SIZE * FRAME_COUNT }> = Arena::ZERO;

/// The dispatch-callback slot the production [`KernelDispatchHook`] is
/// installed into (one slot per binary, set once). Both the syscall
/// callback and the user-fault resolver resolve through it.
static DISPATCH_SLOT: DispatchCallbackSlot = DispatchCallbackSlot::new();

/// Per-CPU storage backing the scheduler's arch handle.
static SCHED_STORAGE: RiscvArchStorage<1> = RiscvArchStorage::new();

/// Per-CPU storage backing the dispatch hook + spawn ctx arch handle.
static HOOK_ARCH_STORAGE: RiscvArchStorage<1> = RiscvArchStorage::new();

/// This vertical binds no IRQ lines; the fail-closed controller mirrors
/// what `kernel/core::init` installs when a port exposes no routing.
static IRQ_CONTROLLER: UnsupportedController = UnsupportedController;

fn note(id: EventId, message: &'static str) {
    log(
        &SERIAL_SINK,
        &Event {
            level: Level::Info,
            id,
            message,
            fields: &[],
        },
    );
}

/// Forward to the shared riscv64 panic bridge (parks the hart; the run then
/// times out and the harness reports the failure).
#[panic_handler]
fn code_install_qemu_riscv64_panic(info: &PanicInfo<'_>) -> ! {
    handle_panic_via_serial(info)
}

/// The syscall-dispatch callback every program's `ecall` traps reach. It
/// mirrors the production bin-crate callback (`dispatch_riscv64`): read the
/// kernel-stack args frame and forward through the resident production
/// [`KernelDispatchHook`] via the shared `dispatch_via_slot` bridge. An
/// empty slot or a missing caller context fails the test loudly.
extern "C" fn dispatch(number: u64, args_ptr: *const [u64; SYSCALL_MAX_ARGS]) -> u64 {
    // SAFETY: the trap trampoline lays the frame out on the kernel
    // stack and only invokes us with a valid pointer; the array lives at
    // least until we return.
    let args = unsafe { read_raw_args(args_ptr) };
    match dispatch_via_slot(&DISPATCH_SLOT, number, args) {
        Some(value) => value,
        None => qemu_exit::exit_failure(FAIL_NO_DISPATCH),
    }
}

/// The user-fault resolver the S-mode trap path calls for every U-mode
/// load/store page fault: the exact production glue, bound to this
/// vertical's own slot, so the `tairix-rt` heap and the compiler's written
/// page are demand-backed as they are in production.
// The callback matches the arch `UserFaultResolveFn` type (a bare safe
// `extern "C" fn`); the raw pointer is only forwarded into the guarded
// `unsafe` call below, which narrows it with `as_ref`.
#[allow(clippy::not_unsafe_ptr_arg_deref)]
extern "C" fn code_install_user_fault(
    stval: u64,
    write: bool,
    regs: *const tairix_arch_api::backtrace::UserRegisterFrame,
) -> bool {
    // SAFETY: the trap handler builds the frame on its kernel stack and
    // holds it live across this call, or passes null; the slot helper
    // narrows the pointer with `as_ref` and never dereferences null.
    unsafe { resolve_user_fault_via_slot(&DISPATCH_SLOT, stval, write, regs) }
}

/// The capability set the parent runs under: `PROC_SPAWN` to start its
/// workers, sandboxed or not, and `JIT_MAP_EXEC`, the subject. A worker's
/// registry row requests nothing, so the one unsandboxed worker holds nothing
/// either.
fn parent_caps() -> CapabilitySet {
    let mut caps = CapabilitySet::empty();
    caps.insert(CapabilityId::PROC_SPAWN);
    caps.insert(CapabilityId::JIT_MAP_EXEC);
    caps
}

/// The program registry the production `spawn` syscall resolves the
/// parent's worker path against: the fixture's one `rxe` in its worker role.
static CHILD_PROGRAMS: [EmbeddedProgram; 1] = [EmbeddedProgram {
    path: b"/bin/ci-worker",
    rxe: PROGRAM_RXE,
    caps: &[],
    args: &[b"/bin/ci-worker", b"worker"],
}];

/// The registry over [`CHILD_PROGRAMS`].
static PROGRAMS: ProgramRegistry = ProgramRegistry::new(&CHILD_PROGRAMS);

/// Bring the board up: parse the live `virt` device tree OpenSBI passed in
/// `a1` for the timebase, install the S-mode trap vector, and install the
/// dispatch callback + user-fault resolver. The kernel itself runs with
/// bring paging up through the one production sequence
/// (`boot_riscv64::enable_paging_and_direct_map`) — the boot identity space
/// plus the direct physical map — because the production spawn producer
/// reaches each child's Sv39 tables *through* that map. Returns the
/// discovered timebase.
fn bring_up_board(dtb: u64) -> u64 {
    // SAFETY: `dtb` is the verbatim `a1` pointer from OpenSBI; it addresses
    // a valid flattened device tree that lives for the life of the guest.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(dtb as *const u8) }) else {
        qemu_exit::exit_failure(FAIL_FDT);
    };
    // The boot seed, captured as the boot path captures it: on a core with
    // no hardware RNG it is the reserve's one dependable source.
    if let Some(seed) = fdt.chosen_rng_seed() {
        tairix_kernel_core::random::capture_boot_entropy_seed(seed);
    }
    let Some(timebase_hz) = fdt.timebase_frequency() else {
        qemu_exit::exit_failure(FAIL_ZERO_FREQ);
    };
    if timebase_hz == 0 {
        qemu_exit::exit_failure(FAIL_ZERO_FREQ);
    }

    // Bring paging up before the trap vector, so the handler address the
    // vector names resolves under the regime that will be in force. A
    // refusal is fatal: the producer cannot reach a child's tables without
    // the map.
    // SAFETY: `dtb` is the verbatim `a1` pointer (as above), and this is the
    // boot hart's single call.
    if boot_riscv64::enable_paging_and_direct_map(dtb).is_err() {
        qemu_exit::exit_failure(FAIL_PAGING);
    }

    // Install the trap vector + the callbacks before any user task runs.
    // SAFETY: called once on the boot hart with a stack established.
    unsafe { trap::init_traps() };
    syscall_entry::set_dispatch_callback(dispatch);
    // Bind the production user-fault resolver to this vertical's slot.
    if tairix_arch_api::fault::set_user_fault_resolver(code_install_user_fault).is_err() {
        qemu_exit::exit_failure(FAIL_RESOLVER_INSTALL);
    }
    timebase_hz
}

/// The leaked-`'static` kernel subsystems the production dispatch hook and
/// spawn context borrow — the vertical's analogue of `KernelState`, lifted
/// by one-shot `Box::leak` publishes exactly as `kernel_core::kernel_main`
/// does (a one-shot publish, not a global mutable static).
struct Subsystems {
    frames: &'static FrameAllocator,
    sched: &'static Scheduler<RiscvBinArch>,
    arch: &'static RiscvBinArch,
    caps: &'static RwLock<CapTable>,
    peer_watch: &'static tairix_kernel_core::PeerWatch,
    ipc: &'static RwLock<PortRegistry>,
    aspaces: &'static RwLock<AddressSpaceRegistry>,
    rng: &'static RwLock<Box<dyn RandomReserve + Send + Sync>>,
    irq_table: &'static IrqTable,
}

/// Build the live kernel subsystems: the `kernel/mem` frame allocator over
/// the identity-mapped pool (so the spawn producer and the demand-fault
/// path draw their frames from the production path), the scheduler over
/// the production `KernelArch` wrapper, and the capability / port /
/// address-space / random / IRQ state the production hook borrows.
fn leak_subsystems(counter_hz: u64) -> Subsystems {
    let mut memory_map = BootMemoryMap::new();
    memory_map.push(MemoryRegion {
        start: PhysAddr::new(FRAME_POOL.as_mut_ptr() as u64),
        length: (PAGE_SIZE * FRAME_COUNT) as u64,
        kind: RegionKind::Usable,
    });
    let Ok(frames) = FrameAllocator::new(&memory_map) else {
        qemu_exit::exit_failure(FAIL_FRAMES);
    };
    let frames: &'static FrameAllocator = Box::leak(Box::new(frames));

    let sched_arch = Arc::new(RiscvBinArch::new(
        RiscvArch::new(&SCHED_STORAGE, BOOT_CPU, counter_hz),
        None,
    ));
    // Seeded as the kernel's is, since a child's stack canary is drawn from it.
    let Ok((reserve, _)) = tairix_kernel_core::random::seeded_reserve(&sched_arch) else {
        qemu_exit::exit_failure(FAIL_SEED);
    };
    let Ok(sched) = Scheduler::new(SchedulerConfig::defaults_for(1), sched_arch) else {
        qemu_exit::exit_failure(FAIL_SCHED_NEW);
    };

    Subsystems {
        frames,
        sched: Box::leak(Box::new(sched)),
        arch: Box::leak(Box::new(RiscvBinArch::new(
            RiscvArch::new(&HOOK_ARCH_STORAGE, BOOT_CPU, counter_hz),
            None,
        ))),
        caps: Box::leak(Box::new(RwLock::new(CapTable::new()))),
        peer_watch: Box::leak(Box::new(tairix_kernel_core::PeerWatch::new())),
        ipc: Box::leak(Box::new(RwLock::new(PortRegistry::new()))),
        aspaces: Box::leak(Box::new(RwLock::new(AddressSpaceRegistry::new()))),
        rng: Box::leak(Box::new(RwLock::new(
            Box::new(reserve) as Box<dyn RandomReserve + Send + Sync>
        ))),
        irq_table: Box::leak(Box::new(IrqTable::new(0))),
    }
}

/// Boot entry point — the symbol the arch crate's boot trampoline calls
/// with the boot hart id in `a0` and the device-tree pointer in `a1`.
#[no_mangle]
pub extern "C" fn kernel_main(hartid: u64, dtb: u64) -> ! {
    note(TEST_START, "riscv64 code-install test: starting");

    if hartid != u64::from(BOOT_CPU) {
        qemu_exit::exit_failure(FAIL_UNEXPECTED_HART);
    }
    let counter_hz = bring_up_board(dtb);

    // The fixture `rxe`'s baked relocations must target the bias the
    // production producer maps every child at; a drifted constant would
    // admit a child whose pointers do not match its mapping (fail closed).
    if USER_BIAS != CHILD_USER_BIAS {
        qemu_exit::exit_failure(FAIL_BIAS);
    }

    let sys = leak_subsystems(counter_hz);

    // Publish the wait-queue arch hook so parked waiters (the parent in
    // `wait`) are genuinely unparked by their wake events — the same
    // adapter the production boot path installs.
    let wait_arch = SchedWaitQueueArch::leak(sys.sched, sys.arch);
    if tairix_kernel_core::waitq::install_wait_arch(wait_arch).is_err() {
        qemu_exit::exit_failure(FAIL_HOOK_INSTALL);
    }

    // The scheduler-side process-wait producer: records every parent/child
    // link the production spawn paths register and backs the production
    // `wait` syscall the parent blocks in.
    let wait_producer: &'static KernelProcessWait<RiscvBinArch> =
        Box::leak(Box::new(KernelProcessWait::new(sys.arch)));

    // The production live-space producer: serves the `mem_map` pair and the
    // one-page-per-fault backing the user-fault resolver maps through it.
    let live: &'static LiveMemMap<RiscvBinArch> = Box::leak(Box::new(LiveMemMap::new(sys.arch)));

    // Publish the production dispatch hook: every syscall the programs
    // issue — `spawn`, `code_install`, `mem_unmap`, `wait`, `exit` — and every
    // user-fault resolution runs the production handler path.
    // Size the futex bucket table from this chassis's CPU count, as the boot
    // path does: correctness never depends on the count, only contention, but
    // an unsized table would serialise unrelated keys.
    tairix_kernel_core::futex::init_buckets(1);

    // The scheduler-side process-signal producer, as production carries it:
    // every process's teardown lands through it. Built before the hook, which
    // carries it; the hook becomes its landing seam once it exists.
    let signal_producer = Box::leak(Box::new(tairix_kernel_core::KernelProcessSignal::new(
        wait_producer,
        sys.sched,
        sys.caps,
    )));

    let hook: &'static KernelDispatchHook<'static, RiscvBinArch> = Box::leak(Box::new(
        KernelDispatchHook::new(
            sys.sched,
            sys.caps,
            sys.arch,
            &SERIAL_SINK,
            sys.irq_table,
            &IRQ_CONTROLLER,
            sys.ipc,
            sys.aspaces,
            sys.rng,
            &RISCV_UART_CONSOLES,
            sys.frames,
            sys.frames,
            &PROGRAMS,
            wait_producer,
            // No seat / MMIO / DMA surface in this vertical; those producers
            // stay fail-closed.
            &NULL_SEAT_REGISTRY,
            live,
            &NULL_MMIO_MAP_FACILITY,
            &NULL_DMA_ALLOC_FACILITY,
        )
        .with_peer_watch(sys.peer_watch)
        .with_process_signal(signal_producer),
    ));
    if DISPATCH_SLOT.install_dispatcher(hook).is_err() {
        qemu_exit::exit_failure(FAIL_HOOK_INSTALL);
    }

    // Publish the leaked hook as the signal producer's landing seam, so every
    // teardown lands through the one shared rule, and the producer as the
    // dispatch loop's deferred-kill lander.
    if signal_producer.install_task_reclaim(hook).is_err() {
        qemu_exit::exit_failure(FAIL_HOOK_INSTALL);
    }
    if tairix_kernel_core::install_deferred_kill_lander(signal_producer).is_err() {
        qemu_exit::exit_failure(FAIL_HOOK_INSTALL);
    }

    // Spawn the parent role through the production runtime-spawn seam
    // (`KernelSpawnCtx` assembly inside `KernelInitSpawner`), recorded
    // against the kernel supervisor identity so this chassis can reap it.
    // Publish the launch-services bundle the deferred child-load path reads:
    // the arch image builder builds each admitted child's image on the
    // child's own first slice, off this chassis's cooperative drive. The one
    // shared build+publish the production boot path uses.
    let _ = tairix_kernel_core::spawn_services::install_over(
        sys.arch,
        sys.frames,
        &SERIAL_SINK,
        &tairix_kernel_core::NULL_FILESYSTEM,
        None,
        sys.aspaces,
        sys.caps,
        sys.peer_watch,
        wait_producer,
        &RISCV_PROCESS_SPAWN,
        sys.rng,
    );

    let init_ctx = KernelInitSpawner::new(
        sys.frames,
        &SERIAL_SINK,
        sys.sched,
        sys.caps,
        sys.peer_watch,
        sys.aspaces,
        sys.arch,
        wait_producer,
        sys.irq_table,
        &IRQ_CONTROLLER,
        &NULL_SHARED_MEM_FACILITY,
        KernelArch::cross_cpu_tlb_shootdown(sys.arch),
    );
    let Ok(parent_pid) = init_ctx.spawn_driver_process(
        "/bin/ci-parent",
        PROGRAM_RXE,
        parent_caps(),
        &[],
        &[b"/bin/ci-parent", b"parent"],
        None,
    ) else {
        qemu_exit::exit_failure(FAIL_SPAWN);
    };
    note(
        TEST_SPAWNED,
        "riscv64 code-install test: parent spawned through the production seam",
    );

    // The budget-bounded cooperative drive: step the scheduler and poll the
    // wait producer for the parent's exit between steps. A parent exit of 0
    // is the PASS, anything else names the failing check through its code.
    // A task id never exceeds the ABI's pid bound, so reinterpreting it as
    // the signed pid the wait ABI carries is exact.
    let parent_pid = parent_pid.cast_signed();
    let mut steps = 0u64;
    while steps < MAX_STEPS {
        let _ = sys.sched.step(BOOT_CPU);
        steps += 1;

        // Deliver any wake a handler deferred while the task ran — the same
        // between-dispatches service the production loop performs; without
        // it a child's `exit` never unparks the parent blocked in `wait`.
        let _ = tairix_kernel_core::waitq::drain_pending_wakes();

        match wait_producer.poll(
            ProcessId(0),
            parent_pid,
            WaitFlags::empty(),
            &mut |_| Ok(()),
        ) {
            Ok(reaped) => match reaped.status {
                WaitStatus::Exited(0) => {
                    note(
                        TEST_PASS,
                        "riscv64 code-install test: parent verified every install and exited 0",
                    );
                    qemu_exit::exit_success();
                }
                WaitStatus::Exited(code) => {
                    qemu_exit::exit_failure(fail_code(FAIL_EXIT_BASE, code));
                }
                WaitStatus::Stopped(_) => {
                    qemu_exit::exit_failure(FAIL_PARENT_STOPPED);
                }
            },
            Err(Errno::WouldBlock) => {}
            Err(_) => qemu_exit::exit_failure(FAIL_POLL),
        }

        // A fully drained workload without a reapable parent means the
        // parent vanished down a path that never recorded its exit; fail
        // with a distinct finisher rather than spinning out the watchdog.
        if sys.sched.live_task_count() == 0 {
            qemu_exit::exit_failure(FAIL_DRAINED);
        }
    }
    qemu_exit::exit_failure(FAIL_DEADLOCK);
}
