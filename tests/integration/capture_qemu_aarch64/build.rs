//! Build script for the screen-capture QEMU vertical: the aarch64 `virt`
//! vertical build, and on every target the desktop's capture record ids and
//! kept-capture names the contract borrows (`contract.rs`), from their own
//! definitions, so the guest links none of the desktop.

use std::env;
use std::fs;
use std::path::PathBuf;

use tairix_desktop_session::capture::{
    CaptureTarget, Kept, CAPTURE_KEPT, CAPTURE_REFUSED, CAPTURE_TAKEN, NOTHING_LOST,
    RECORDING_ENDED,
};

fn main() {
    tairix_itest_harness::aarch64_virt_guest_build(1);

    let out_dir = env::var_os("OUT_DIR").expect("OUT_DIR set by cargo");
    let contract = format!(
        "// Auto-generated by build.rs. DO NOT EDIT.\n\
         /// The desktop's record of a still composed.\n\
         pub const CAPTURE_TAKEN: u32 = {taken};\n\
         /// The desktop's record of a capture given its name in its folder.\n\
         pub const CAPTURE_KEPT: u32 = {kept};\n\
         /// The desktop's record of a capture it did not take.\n\
         pub const CAPTURE_REFUSED: u32 = {refused};\n\
         /// How a kept still is named in its record.\n\
         pub const KEPT_STILL: &str = {still:?};\n\
         /// How a kept leftover of an earlier session is named in its record.\n\
         pub const KEPT_LEFTOVER: &str = {leftover:?};\n\
         /// How a still of the whole screen is named in its record.\n\
         pub const TARGET_SCREEN: &str = {screen:?};\n\
         /// The desktop's record of a recording ended.\n\
         pub const RECORDING_ENDED: u32 = {ended};\n\
         /// How a kept recording is named in its record.\n\
         pub const KEPT_RECORDING: &str = {recording:?};\n\
         /// How an ended recording that lost nothing is named in its record.\n\
         pub const NOTHING_LOST: &str = {nothing:?};\n",
        taken = CAPTURE_TAKEN.0,
        kept = CAPTURE_KEPT.0,
        refused = CAPTURE_REFUSED.0,
        still = Kept::Still.as_str(),
        leftover = Kept::Leftover.as_str(),
        screen = CaptureTarget::Screen.as_str(),
        ended = RECORDING_ENDED.0,
        recording = Kept::Recording.as_str(),
        nothing = NOTHING_LOST,
    );
    fs::write(PathBuf::from(&out_dir).join("contract.rs"), contract).expect("write contract.rs");
}
