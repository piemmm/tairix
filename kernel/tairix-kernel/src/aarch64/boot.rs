/// Audit event: the aarch64 production kernel reached its Stage-P1 boot
/// init point. Sits in the `kernel/core`-owned `4000..5000` range (per
/// `lib/log`'s subsystem ranges), just below the x86_64 boot pipeline's
/// `4098`/`4099`; the id is part of the audit contract and may not be
/// renumbered.
const KERNEL_BOOT_AARCH64_REACHED: EventId = EventId(4097);

/// Audit event: the boot path discovered the platform PCIe root complex the
/// port describes and recorded its address windows. Logged once, so a metal
/// capture shows the windows found when a device behind it is silent. In the `kernel/core`-owned `4000..5000` range, clear of the ids
/// around it; part of the audit contract, never renumbered.
const KERNEL_PCIE_DISCOVERED: EventId = EventId(4100);

/// Audit event: the boot path asked the firmware that owns the ARM clock to
/// run the cores at their full rate, before anything else ran. Logged once,
/// so a metal capture states the speed the rest of boot actually
/// ran at — the firmware leaves the clock at `arm_freq_min` until something
/// asks, and a board silently stuck there is otherwise only visible as
/// everything being slow. Sits in the `kernel/core`-owned `4000..5000` range,
/// clear of the ids above; the id is part of the audit contract and may not
/// be renumbered.
const KERNEL_CPU_CLOCK_RAISED: EventId = EventId(4101);

/// Audit event: a started secondary CPU left the kernel dispatch loop
/// (hand-off refused or scheduler stopped) and is parking fail-closed.
/// Sits in the `kernel/core`-owned `4000..5000` range, clear of the ids
/// above and of `kernel/core`'s own `40xx` block; the id is part of the
/// audit contract and may not be renumbered.
const KERNEL_SECONDARY_PARKED: EventId = EventId(4102);

/// Stable `"true"`/`"false"` audit-field value for a boolean condition.
/// Keeping the boot log to `&'static str` fields means the path takes no
/// allocation and cannot panic.
const fn yes_no(value: bool) -> &'static str {
    if value {
        "true"
    } else {
        "false"
    }
}

extern "C" {
    /// First byte of the kernel image, at its link address, defined by the
    /// board linker script `build.rs` selects.
    #[cfg(feature = "watchdog-diagnostics")]
    static __kernel_start: u8;
    /// One byte past the end of the kernel image, including the boot heap,
    /// at its link address.
    static __kernel_end: u8;
}

/// Link address of the kernel image's first byte, which a diagnostics
/// build renders program counters relative to.
#[cfg(feature = "watchdog-diagnostics")]
pub(crate) fn kernel_start_addr() -> u64 {
    // `addr_of!` reads the marker's address without forming a reference to
    // the zero-sized, never-dereferenced symbol.
    core::ptr::addr_of!(__kernel_start) as u64
}

/// Physical address one past the kernel image: the usable physical-memory
/// region the allocator receives begins at the next page boundary after it.
fn kernel_phys_end() -> u64 {
    // `addr_of!` reads the marker's address without forming a reference to
    // the zero-sized, never-dereferenced symbol.
    tairix_arch_aarch64::paging::image_phys(core::ptr::addr_of!(__kernel_end) as u64)
}

/// The retained, tail-able in-memory boot audit ring for this port.
///
/// Composed into the boot audit channel through [`AUDIT_SINK`], so every
/// audit record the kernel emits from the earliest boot onward is teed into
/// it and can be read back non-destructively — the store the pre-boot
/// Supervisor's `log` command tails (`plans/NEW-SUPERVISOR.md`). It is
/// guarded by the aarch64 [`DaifIrqControl`], so a record copy masks this
/// CPU's interrupts for its short, allocation-free duration and the ring is
/// safe to write from an interrupt handler that logs. It stamps each record
/// with the kernel's monotonic since-boot clock ([`boot_audit_clock`]).
pub static BOOT_AUDIT_RING: BootAuditRing<BOOT_AUDIT_RING_CAPACITY, DaifIrqControl> =
    BootAuditRing::new(boot_audit_clock);

/// The production boot **audit** channel: a fan-out delivering each record to
/// both the kernel's log sink ([`crate::console_layout::LOG_SINK`], the PL011
/// line and the screen a user sees) and the retained [`BOOT_AUDIT_RING`].
///
/// `main.rs` passes this as [`BootInfo`]'s audit sink for the production
/// binary; the QEMU boot verticals substitute their own audit sink through
/// [`boot`] directly, so retaining the trail is a production-only wiring and
/// never disturbs a test's audit interception.
pub static AUDIT_SINK: TeeSink<'static, 2> =
    TeeSink::new([&crate::console_layout::LOG_SINK, &BOOT_AUDIT_RING]);

/// Record the full rate firmware was asked to run the cores at for boot.
fn log_cpu_clock_raised(log_sink: &dyn Sink, rate_hz: u64) {
    let mut rate_buf = [0u8; 20];
    log(
        log_sink,
        &Event {
            level: Level::Info,
            id: KERNEL_CPU_CLOCK_RAISED,
            message: "aarch64: firmware asked to run the ARM cores at full rate for boot",
            fields: &[Field {
                key: "rate_hz",
                value: tairix_log::FieldValue::Str(format_u64(rate_hz, &mut rate_buf)),
            }],
        },
    );
}

/// Boot the aarch64 kernel on the boot CPU and hand off to
/// [`tairix_kernel_core::kernel_main`].
///
/// `tree` is where the kernel reads the firmware's device tree, read only
/// (`paging::firmware_tree`), or a tree a QEMU vertical embeds, or `0`; it
/// is parsed for the console base, the GIC, the `/memory` windows, the
/// generic-timer rate, and the PSCI conduit.
///
/// `log_sink` / `audit_sink` are the `&'static` sinks installed in the
/// [`BootInfo`]: in production both are the port's PL011-backed
/// [`tairix_arch_aarch64::SERIAL_SINK`]; the boot-completed QEMU vertical
/// substitutes an audit sink that exits QEMU on `AuditEvent::BootCompleted`.
///
/// `log_level` is the initial global log filter `kernel_main` installs
/// (`BootInfo::log_level`). Production passes [`Level::Info`]; an audit
/// observer vertical that must see the `Debug`-level allow records (e.g.
/// `SyscallInvoked`, `EventId(5000)`) passes [`Level::Debug`].
///
/// `hw_tree` is the [`HwTreeSource`] the `hw_tree_read` / `hw_tree_wait`
/// syscalls serve. In production it is the authoritative
/// [`crate::hwtree_store::HW_TREE_SOURCE`]; it is injected here — the same
/// dependency-injection seam the `log_sink`/`audit_sink` use — so the
/// device-manager reactive vertical can install a source that observes
/// `devmgr`'s own read/wait activity and drives its proof deterministically
/// off it, without a compiled-in test back-channel. Only the aarch64 port
/// takes this seam: it is the only one whose reactive-observe vertical needs
/// it, so adding it to the other ports would be an unused parameter.
///
/// Returns the bottom type. On success it enters
/// [`tairix_kernel_core::kernel_main`], which drives the init phases and
/// itself never returns. If the handover cannot be assembled (no usable
/// `/memory` window, an unusable timer, or
/// `BootInfo::validate` rejects the hand-off) it records the boot line
/// and parks the CPU forever via [`halt_current_cpu`] (fail closed).
///
/// # SAFETY-INVARIANT
///
/// Called exactly once, on the boot CPU, from the arch trampoline after
/// `boot.s`'s invariants hold and the port entry moved it onto the kernel
/// root (EL1, interrupts masked, stack established, `.bss` zeroed, FP/SIMD
/// enabled with the vectors).
pub fn boot(
    tree: u64,
    heap: &'static tairix_kalloc::FreeListAllocator,
    log_sink: &'static (dyn Sink + Sync),
    audit_sink: &'static (dyn Sink + Sync),
    log_level: Level,
    hw_tree: &'static (dyn tairix_kernel_core::HwTreeSource + 'static),
) -> ! {
    // Make every kernel heap's lock interrupt-safe before anything can be
    // interrupted while holding one: install this port's per-CPU DAIF
    // mask/restore. Done here, at boot entry — before the first heap
    // allocation, before interrupts are ever enabled, and before any
    // secondary CPU is started — so no interrupt can ever fire on a CPU
    // mid-allocation and reenter the allocator, spinning forever on the lock
    // its own interrupted mainline holds (a single-CPU self-deadlock). One
    // install covers every core and every heap the binary holds: the hooks
    // mask the *current* CPU's interrupts and are read by the allocator
    // itself, so a heap the boot handover never names is covered too. It
    // stores two `fn` pointers and does not allocate, so it is safe before
    // the heap has grown.
    tairix_kalloc::install_irq_control(
        crate::aarch64::gic_irq::kalloc_irq_disable,
        crate::aarch64::gic_irq::kalloc_irq_restore,
    );

    // Before anything that can fault: with the slot empty an exception parks
    // the CPU mute, and the report flushes the lines still queued. A QEMU
    // vertical observing its own faults installed first and keeps its own.
    let _ = crate::aarch64::panic_ctx::install_fatal_reports();

    // Type the direct map from the board the tree describes before any
    // device is brought up: registers first, so no RAM ever shares a
    // gigabyte with them.
    let typed = type_direct_map(tree);

    // P2 + P3: point the console and the GIC at what the tree describes and
    // bring the framebuffer boot console's surface up.
    let early = configure_mmio_from_dtb(tree);
    if !typed.ram_windows.is_empty() {
        // Every gigabyte is one L1 block descriptor but the image's own.
        crate::mem_map::log_direct_map(log_sink, paging::physmap_gigapages(), true);
    }

    // The console's grids need the heap, so it is attached here rather than
    // at display discovery. With no display, or a scan-out the active root
    // does not cover, the UART keeps the console and the boot record says
    // so.
    let video_console = crate::console_layout::CONSOLE.attach(None);

    crate::protections::log(
        log_sink,
        [("pan", tairix_arch_aarch64::protection::pan_in_force())],
    );

    if let Some(pcie) = early.pcie {
        log_pcie_discovery(log_sink, &pcie);
    }

    if early.cpu_clock_hz != 0 {
        log_cpu_clock_raised(log_sink, early.cpu_clock_hz);
    }

    // The timer rate, the PSCI conduit and the CPUs (P4 + P5). A null,
    // unreadable, or incomplete tree leaves the `virt` defaults in place
    // (fail closed).
    let discovered = configure_from_dtb(tree);
    let installed_memory_bytes = typed.installed_bytes;
    let ram_windows = typed.ram_windows;
    let direct_map = !ram_windows.is_empty();

    let (arch, cpu_mpidrs) = build_cpu_topology_and_arch(&discovered, tree);
    let (arch, smp_start_method) = select_secondary_start(arch, &discovered, &cpu_mpidrs);

    // Sanity-check that the constructed handle reports the boot CPU, and
    // that the generic-timer frequency is usable. A zero frequency would
    // make the monotonic clock unusable.
    let boot_cpu_ok = arch.current_cpu() == BOOT_CPU;
    let timer_present = discovered.timer_hz != 0;

    // Stage the secondary bring-up (stacks + entry + the dense-id →
    // affinity table the spin-table trampoline recovers identity from)
    // before the hand-off: `kernel_main` issues the starts (PSCI
    // `CPU_ON` or spin-table release) once every init phase is green,
    // and each start is refused fail-closed (and audited) unless this
    // preparation succeeded. Single-CPU boots prepare nothing.
    let smp_prepared = prepare_secondary_bringup(&cpu_mpidrs);

    // P6c-1: translate the firmware-discovered `/memory` windows into the
    // canonical physical-memory map `kernel_core::kernel_main` consumes,
    // with the firmware blob reserved out of it.
    let layout_result =
        build_boot_memory_layout(&ram_windows, tairix_arch_aarch64::paging::firmware_tree());
    let (mem_status, usable_bytes, reserved_bytes) = match &layout_result {
        Ok(map) => {
            let (usable, reserved) = region_byte_totals(map);
            ("built", usable, reserved)
        }
        Err(status) => (*status, 0, 0),
    };
    let mem_map_built = layout_result.is_ok();

    let ready = boot_cpu_ok && timer_present && mem_map_built && direct_map;

    log_boot_line(
        log_sink,
        &BootStatus {
            level: if ready { Level::Info } else { Level::Warn },
            boot_cpu_ok: yes_no(boot_cpu_ok),
            timer_present: yes_no(timer_present),
            dtb_present: yes_no(tree != 0),
            console_discovered: yes_no(early.console),
            gic_discovered: yes_no(early.gic),
            video_console: yes_no(video_console),
            fb_base: early.video.map_or(0, |v| v.fb_base),
            fb_len: early.video.map_or(0, |v| v.fb_len_bytes),
            boot_root: tairix_arch_aarch64::paging::park_root().unwrap_or(0),
            device_gigapages: typed.registers[0],
            ram_discovered: yes_no(!ram_windows.is_empty()),
            mem_map_built: yes_no(mem_map_built),
            direct_map: yes_no(direct_map),
            mem_status,
            usable_bytes,
            reserved_bytes,
            timer_hz_from_tree: yes_no(discovered.timer_hz_from_tree),
            timer_hz: discovered.timer_hz,
            smp_start_method,
            cpu_count: cpu_mpidrs.len(),
            smp_prepared: yes_no(smp_prepared),
        },
    );

    // Hand off to the architecture-neutral kernel core when the handover
    // is sound; otherwise park fail-closed. The map is
    // moved into `BootInfo` here, so it is built exactly once.
    if ready {
        if let Ok(map) = layout_result {
            // Record the discovered tree and the root block binding before
            // entering the core. The early-discovered video facts ride along
            // so the boot display joins the same tree (`plans/DISPLAY.md` D7d).
            let placement = audit_root_storage_binding(
                tree,
                early.video,
                &discovered.gic_redistributors,
                discovered.gic_redistributor_stride,
                log_sink,
            );
            place_video_console(placement, video_console, early.video);
            let gic_redistributors: &'static [gicv3::RedistributorRegion] =
                Box::leak(discovered.gic_redistributors.into_boxed_slice());
            enter_kernel_core(
                Aarch64BinArch::new(arch).with_gic_redistributors(
                    gic_redistributors,
                    discovered.gic_redistributor_stride,
                ),
                BootMemory {
                    map,
                    installed_bytes: installed_memory_bytes,
                },
                heap,
                log_sink,
                audit_sink,
                log_level,
                hw_tree,
            )
        }
    }

    // The handover was rejected (see the boot-log line's fields for which
    // check failed); park fail-closed.
    halt_current_cpu()
}

/// What the boot typed the direct map with.
struct TypedRam {
    /// The gigabytes typed as registers.
    registers: [u64; GIGAPAGE_MASK_WORDS],
    /// Every `/memory` window the direct map covers as RAM, in tree order:
    /// the RAM the allocator may use. An 8 GiB board may declare several
    /// (below the MMIO hole, 1 GiB..4 GiB, and above 4 GiB). Empty when the
    /// tree declares none or is malformed (fail closed — no memory map is
    /// built).
    ram_windows: Vec<(u64, u64)>,
    /// Bytes of RAM the tree declares, reachable or not.
    installed_bytes: u64,
}

/// Point the console and the interrupt controller at what `tree` describes,
/// and type the direct map from the board: the gigabytes those, the
/// firmware's doorbell, `fw_cfg` and the PCIe root complex lie in as
/// registers, a generic ECAM host's configuration regions as such, and then
/// what is left of the `/memory` windows as RAM.
///
/// Registers win a gigabyte they share with RAM: a Normal alias of a register
/// invites the core's speculative reads into it, which wedged metal hardware
/// while QEMU, which answers every address, stayed green. That RAM is lost to
/// the allocator until the map is typed at a finer grain (`plans/APPS.md`
/// I4). The image's own gigabyte is RAM, typed by the port entry, so no
/// register a board reports there can retype it. A null, unreadable, or
/// incomplete tree leaves the `virt` defaults in place (fail closed).
///
/// The boot records how wide the RAM map came out once the console is up
/// ([`TypedRam::ram_windows`]), so a machine whose RAM outruns the
/// architectural ceiling is visible in the transcript rather than found later
/// as a fail-closed allocation.
fn type_direct_map(tree: u64) -> TypedRam {
    let mut asked = [0u64; GIGAPAGE_MASK_WORDS];
    let mut config = [0u64; GIGAPAGE_MASK_WORDS];
    let mut windows = Vec::new();
    // SAFETY: `tree` is null or the firmware tree the port entry mapped read
    // only for the kernel's life; `Fdt::from_ptr` checks its magic and bounds
    // the blob by its own `totalsize` before any further read.
    let fdt = (tree != 0)
        .then(|| unsafe { Fdt::from_ptr(tree as *const u8) }.ok())
        .flatten();
    let mut add = |base: u64, len: u64| {
        for (word, extent) in asked
            .iter_mut()
            .zip(gigapage_mask_from_extents(&[(base, len.max(1))]))
        {
            *word |= extent;
        }
    };
    if let Some(fdt) = &fdt {
        let _ = console::configure_from_fdt(fdt);
        let _ = gic::configure_from_fdt(fdt);
        gic::for_each_window(fdt, &mut add);
        video::register_windows(fdt, &mut add);
        if let Some(pcie) = platform::pcie_bringup(fdt) {
            add(pcie.regs_phys, pcie.regs_len);
            add(pcie.outbound_cpu_base, pcie.outbound_size);
        }
        if fdt.find_compatible(tairix_fdt::pci::ECAM_HOST).is_some() {
            config = pci_config_gigapages(fdt);
        }
        // A malformed tree discards the partial collection: the boot then
        // builds no memory map at all rather than trusting a truncated
        // inventory.
        if fdt
            .each_memory_region(|base, size| {
                if size != 0 {
                    windows.push((base, size));
                }
            })
            .is_err()
        {
            windows.clear();
        }
    }
    let (console_base, _) = console::current();
    let (distributor, cpu_interface) = gic::current();
    add(console_base as u64, 1);
    add(distributor as u64, 1);
    add(cpu_interface as u64, 1);

    let typed =
        crate::mem_map::type_board(&asked, &config, &windows, paging::PHYSMAP_REACH, reveal);
    TypedRam {
        registers: typed.registers,
        ram_windows: typed.ram_windows,
        installed_bytes: crate::mem_map::window_byte_total(&windows),
    }
}

/// Record the discovered PCIe root-complex windows once.
///
/// Purely a metal diagnostic: the windows themselves reach the autoloaded
/// user-space bus driver as resource grants on the discovered root
/// complex's hardware-tree node, not through any kernel-side stash
/// (`plans/PI.md` P10 D5d). A capture then shows which register block and
/// inbound/outbound apertures were found, so a silent device can be bisected
/// against the hardware actually present rather than guessed at.
/// Allocation-free hex rendering on the caller's stack.
fn log_pcie_discovery(log_sink: &'static (dyn Sink + Sync), pcie: &platform::PcieDiscovery) {
    let mut regs_base_buf = [0u8; 16];
    let mut regs_len_buf = [0u8; 16];
    let mut aperture_top_buf = [0u8; 16];
    let mut inbound_size_buf = [0u8; 16];
    let mut inbound_pcie_buf = [0u8; 16];
    let mut outbound_cpu_buf = [0u8; 16];
    let mut outbound_pcie_buf = [0u8; 16];
    let mut outbound_size_buf = [0u8; 16];
    log(
        log_sink,
        &Event {
            level: Level::Info,
            id: KERNEL_PCIE_DISCOVERED,
            message: "aarch64: discovered a PCIe root complex",
            fields: &[
                Field {
                    key: "regs_base_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.regs_phys,
                        &mut regs_base_buf,
                    )),
                },
                Field {
                    key: "regs_len_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.regs_len,
                        &mut regs_len_buf,
                    )),
                },
                Field {
                    key: "dma_aperture_top_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.dma_aperture_top,
                        &mut aperture_top_buf,
                    )),
                },
                Field {
                    key: "inbound_size_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.inbound_size,
                        &mut inbound_size_buf,
                    )),
                },
                Field {
                    key: "inbound_pcie_base_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.inbound_pcie_base,
                        &mut inbound_pcie_buf,
                    )),
                },
                Field {
                    key: "outbound_cpu_base_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.outbound_cpu_base,
                        &mut outbound_cpu_buf,
                    )),
                },
                Field {
                    key: "outbound_pcie_base_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.outbound_pcie_base,
                        &mut outbound_pcie_buf,
                    )),
                },
                Field {
                    key: "outbound_size_hex",
                    value: tairix_log::FieldValue::Str(format_hex_u64(
                        pcie.outbound_size,
                        &mut outbound_size_buf,
                    )),
                },
            ],
        },
    );
}

/// Build the [`Aarch64Arch`] handle — the single concrete-arch selection
/// point for the kernel image — and the dense `CpuId` → `MPIDR_EL1` map it
/// is sized from, then classify each core from the firmware tree.
///
/// Every per-CPU backing (the handle's slots, the preemption slices, the
/// secondary stacks, the scheduler's run queues) is sized from that one
/// validated list, exactly to the machine — no compile-time core ceiling.
/// A malformed `/cpus` list falls back closed to a single-CPU map; an
/// allocation failure or a topology wider than `CpuId` parks fail-closed.
/// The core-class walk (`capacity-dmips-mhz`) lets the scheduler place
/// background work on efficiency cores; a missing or malformed tree leaves
/// the homogeneous Performance default.
fn build_cpu_topology_and_arch(discovered: &Discovered, tree: u64) -> (Aarch64Arch, Vec<u64>) {
    let cpu_mpidrs =
        match crate::cpu_topology::order_cpus(&discovered.cpu_mpidrs, smp::current_affinity()) {
            Ok(cpus) => cpus,
            Err(crate::cpu_topology::CpuTopologyError::AllocationFailed) => {
                serial::beacon("pi-boot: CPU topology allocation FAILED, parking");
                halt_current_cpu()
            }
            Err(crate::cpu_topology::CpuTopologyError::TooManyCpus) => {
                serial::beacon("pi-boot: CPU topology exceeds CpuId, parking");
                halt_current_cpu()
            }
        };
    smp::install_current_cpu_index(BOOT_CPU);
    let arch = build_arch_handle(&cpu_mpidrs, discovered.timer_hz);
    if tree != 0 {
        // SAFETY: `tree` is the device tree mapped read only for the
        // kernel's life; `Fdt::from_ptr` checks its magic and bounds it by
        // its own `totalsize`.
        if let Ok(fdt) = unsafe { Fdt::from_ptr(tree as *const u8) } {
            arch.classify_from_fdt(&fdt);
            // The firmware boot seed is the only usable entropy source on an
            // emulated core without `FEAT_RNG` (its cycle counter is
            // deterministic), so without it the CSPRNG would never seed. Input
            // material only, XOR-mixed and DRBG-conditioned kernel-side.
            if let Some(seed) = fdt.chosen_rng_seed() {
                tairix_kernel_core::random::capture_boot_entropy_seed(seed);
            }
            // CoreSight external debug is the one live observation a GIC-400
            // (secure-world FIQ) leaves reachable for a hard-wedged core
            // (`plans/WATCHDOG.md`). A base is installed only when its window
            // is *already* device-mapped, so a read on the lockup path can
            // never fault; with none discovered the sampler reports
            // `Unsupported` and the buddy detector runs unchanged.
            #[cfg(feature = "watchdog-diagnostics")]
            install_debug_component_bases(&fdt, &cpu_mpidrs);
        }
    }
    (arch, cpu_mpidrs)
}

/// Install the secondary-start mechanism the firmware tree declares
/// (`plans/PI.md` P5), never an assumed one (no `cfg(board)` fork).
///
/// A `/psci` node selects PSCI `CPU_ON` over its conduit (`hvc` at
/// EL2-hosted, `smc` at EL3-hosted); a PSCI-less tree whose cpu nodes
/// declare `enable-method = "spin-table"` selects the spin-table release over
/// the declared per-CPU `cpu-release-addr` words, aligned to the dense ids. A
/// tree that declares neither leaves the mechanism unset, and bring-up
/// fails closed at the start site rather than guessing.
fn select_secondary_start(
    arch: Aarch64Arch,
    discovered: &Discovered,
    cpu_mpidrs: &[u64],
) -> (Aarch64Arch, &'static str) {
    if let Some(method) = discovered.psci_method {
        return (
            arch.with_secondary_start(SecondaryStart::Psci(method)),
            "psci",
        );
    }
    let Ok(release_addrs) =
        crate::cpu_topology::align_release_addrs(cpu_mpidrs, &discovered.cpu_spin_releases)
    else {
        serial::beacon("pi-boot: spin-table map allocation FAILED, parking");
        halt_current_cpu()
    };
    if release_addrs.iter().any(|&addr| addr != 0) {
        let release_addrs: &'static [u64] = Box::leak(release_addrs.into_boxed_slice());
        (
            arch.with_secondary_start(SecondaryStart::SpinTable { release_addrs }),
            "spin_table",
        )
    } else {
        (arch, "none")
    }
}

/// Translate the discovered RAM windows into the canonical physical-memory
/// map, with the firmware's device tree reserved out of it.
///
/// An absent or malformed discovery fails closed to a status string rather
/// than a panic. The tree must be reserved because firmware may land it
/// above the kernel image the map already reserves: left usable, the frame
/// allocator or the early-boot RAM self-test (which writes a word of every
/// usable page) would clobber the tree the later root-storage bind and
/// device discovery re-parse. A tree inside the image (a QEMU vertical's
/// embedded one) is reserved with it; no tree reserves nothing.
fn build_boot_memory_layout(
    ram_windows: &[(u64, u64)],
    tree: Option<FirmwareTree>,
) -> Result<tairix_kernel_mem::BootMemoryMap, &'static str> {
    if ram_windows.is_empty() {
        return Err("no_memory_window");
    }
    let mut map = build_memory_map(ram_windows, kernel_phys_end())
        .map_err(crate::mem_map::MemoryMapError::as_str)?;
    if let Some(tree) = tree {
        crate::mem_map::reserve_blob_frames(&mut map, tree.phys, tree.len);
    }
    Ok(map)
}

/// The consolidated aarch64 boot line's report, rendered by [`boot`] so
/// the fields it logs are one record rather than a wall of arguments.
///
/// Each verdict is already the `yes`/`no` string it is logged as; the
/// numeric facts stay numbers and are hex-rendered into
/// [`log_boot_line`]'s own stack buffers.
struct BootStatus {
    /// `Info` on a sound hand-off, `Warn` when a check failed.
    level: Level,
    /// The constructed arch handle reports the boot CPU.
    boot_cpu_ok: &'static str,
    /// The generic-timer frequency is non-zero, so the monotonic clock is
    /// usable.
    timer_present: &'static str,
    /// Firmware handed over a device-tree pointer.
    dtb_present: &'static str,
    /// The direct physical map was sized from the discovered RAM and
    /// installed. Without it the kernel can reach no frame by pointer, so
    /// the hand-off is refused.
    direct_map: &'static str,
    /// A console UART was found in the tree.
    console_discovered: &'static str,
    /// A GIC this port drives was found in the tree.
    gic_discovered: &'static str,
    /// The framebuffer boot console came up.
    video_console: &'static str,
    /// Physical base and byte length of the firmware scan-out, or zeros when
    /// no display came up.
    ///
    /// The console paints this range from arbitrary kernel contexts, so it
    /// must be translatable under whichever root is active. A capture that
    /// shows a fault address inside it says the scan-out was never mapped in
    /// that root; one past its end says a repaint overran
    /// (`plans/OPEN-DEFECTS.md` D81).
    fb_base: u64,
    /// Byte length of the scan-out named by [`Self::fb_base`].
    fb_len: u64,
    /// Physical address of the empty root `TTBR0_EL1` holds while no process
    /// runs.
    ///
    /// A fatal report names the low root that was active (`root=`);
    /// comparing it against this says whether the faulting context ran a
    /// process or the kernel alone, which the address alone cannot
    /// distinguish (`plans/OPEN-DEFECTS.md` D81).
    boot_root: u64,
    /// Low word of the mask of gigabytes the direct map types as registers
    /// (gigabytes 0..64 — both supported boards keep their MMIO below
    /// 64 GiB), so a metal capture shows what was typed (`virt`: 0x1; a board
    /// with its MMIO in gigabyte 3: 0x8).
    device_gigapages: u64,
    /// At least one usable `/memory` window survived the Device clip.
    ram_discovered: &'static str,
    /// The physical-memory map was built.
    mem_map_built: &'static str,
    /// Stable cause string when it was not.
    mem_status: &'static str,
    /// Usable bytes in the built map.
    usable_bytes: u64,
    /// Reserved bytes in the built map.
    reserved_bytes: u64,
    /// The counter rate came from the tree rather than `CNTFRQ_EL0`.
    timer_hz_from_tree: &'static str,
    /// The generic-timer counter rate every `busy_delay_us` settle is
    /// measured against. A value far from the board's crystal means firmware
    /// mis-programmed `CNTFRQ_EL0`, which stretches every bring-up settle
    /// proportionally.
    timer_hz: u64,
    /// Which secondary-start mechanism the tree selected.
    smp_start_method: &'static str,
    /// Dense CPU count every per-CPU structure was sized from.
    cpu_count: usize,
    /// Secondary bring-up staged successfully.
    smp_prepared: &'static str,
}

/// Emit the one consolidated aarch64 boot line.
///
/// Allocation-free: every numeric field is hex-rendered into a stack
/// buffer that outlives the borrowed `fields` slice.
fn log_boot_line(log_sink: &'static (dyn Sink + Sync), status: &BootStatus) {
    let mut usable_buf = [0u8; 16];
    let mut reserved_buf = [0u8; 16];
    let mut device_mask_buf = [0u8; 16];
    let mut timer_hz_buf = [0u8; 16];
    let mut cpu_count_buf = [0u8; 12];
    let mut fb_base_buf = [0u8; 16];
    let mut fb_len_buf = [0u8; 16];
    let mut boot_root_buf = [0u8; 16];
    // Every field of this line is a string, so they are listed as pairs
    // and mapped into the borrowed slice `log` renders.
    let pairs = [
        ("boot_cpu_ok", status.boot_cpu_ok),
        ("timer_present", status.timer_present),
        ("dtb_present", status.dtb_present),
        ("console_discovered", status.console_discovered),
        ("gic_discovered", status.gic_discovered),
        ("video_console", status.video_console),
        (
            "fb_base_hex",
            format_hex_u64(status.fb_base, &mut fb_base_buf),
        ),
        ("fb_len_hex", format_hex_u64(status.fb_len, &mut fb_len_buf)),
        (
            "boot_root_hex",
            format_hex_u64(status.boot_root, &mut boot_root_buf),
        ),
        (
            "device_gigapages_hex",
            format_hex_u64(status.device_gigapages, &mut device_mask_buf),
        ),
        ("ram_discovered", status.ram_discovered),
        ("mem_map_built", status.mem_map_built),
        ("mem_map_status", status.mem_status),
        (
            "usable_bytes_hex",
            format_hex_u64(status.usable_bytes, &mut usable_buf),
        ),
        (
            "reserved_bytes_hex",
            format_hex_u64(status.reserved_bytes, &mut reserved_buf),
        ),
        ("timer_hz_from_tree", status.timer_hz_from_tree),
        (
            "timer_hz_hex",
            format_hex_u64(status.timer_hz, &mut timer_hz_buf),
        ),
        ("smp_start_method", status.smp_start_method),
        (
            "cpu_count",
            tairix_util::fmt::format_usize(status.cpu_count, &mut cpu_count_buf),
        ),
        ("smp_prepared", status.smp_prepared),
        ("direct_map", status.direct_map),
        ("next_stage", "pi_p6c3_spawn_init_el0"),
        ("build_id", KERNEL_BUILD_ID),
    ];
    let fields = pairs.map(|(key, value)| Field {
        key,
        value: tairix_log::FieldValue::Str(value),
    });
    log(
        log_sink,
        &Event {
            level: status.level,
            id: KERNEL_BOOT_AARCH64_REACHED,
            message: "tairix-kernel aarch64: reached stage-p1 boot init point",
            fields: &fields,
        },
    );
}

/// Leak a zeroed `&'static [AtomicU64]` of `count` slots for the arch
/// handle's per-CPU bookkeeping, alive for the kernel's lifetime like
/// the leaked console grids.
fn leak_u64_slots(count: usize) -> Option<&'static [AtomicU64]> {
    let mut slots = Vec::new();
    slots.try_reserve_exact(count).ok()?;
    slots.resize_with(count, || AtomicU64::new(0));
    Some(Box::leak(slots.into_boxed_slice()))
}

/// Leak a zeroed `&'static [AtomicU8]` of `count` slots (the per-CPU
/// core-class table).
fn leak_u8_slots(count: usize) -> Option<&'static [AtomicU8]> {
    let mut slots = Vec::new();
    slots.try_reserve_exact(count).ok()?;
    slots.resize_with(count, || AtomicU8::new(0));
    Some(Box::leak(slots.into_boxed_slice()))
}

/// Build the [`Aarch64Arch`] handle over leaked per-CPU slices sized
/// exactly to the validated dense CPU map.
///
/// `cpu_mpidrs` comes from [`crate::cpu_topology::order_cpus`], which
/// guarantees a non-empty list with the running boot core at dense id
/// 0 — the only ways `with_cpu_slices` can refuse are therefore
/// programmer errors, on which the boot parks fail-closed with a serial
/// beacon rather than continuing over per-CPU state of the wrong shape.
fn build_arch_handle(cpu_mpidrs: &[u64], counter_hz: u64) -> Aarch64Arch {
    let count = cpu_mpidrs.len();
    let Some(cpu_to_mpidr) = leak_u64_slots(count) else {
        serial::beacon("pi-boot: CPU affinity slots allocation FAILED, parking");
        halt_current_cpu()
    };
    let Some(host_ipi_count) = leak_u64_slots(count) else {
        serial::beacon("pi-boot: IPI counter slots allocation FAILED, parking");
        halt_current_cpu()
    };
    let Some(core_classes) = leak_u8_slots(count) else {
        serial::beacon("pi-boot: core-class slots allocation FAILED, parking");
        halt_current_cpu()
    };
    Aarch64Arch::with_cpu_slices(
        cpu_to_mpidr,
        host_ipi_count,
        core_classes,
        BOOT_CPU,
        counter_hz,
        cpu_mpidrs,
    )
    .unwrap_or_else(|| {
        serial::beacon("pi-boot: arch handle construction FAILED, parking");
        halt_current_cpu()
    })
}

/// Leak a zeroed secondary-stack region of `count` slots (one per dense
/// CPU id; slot 0 belongs to the never-started boot CPU).
///
/// Zeroed in place in the heap — never built on the boot stack, whose
/// budget a 64 KiB-per-slot array would blow — and leaked for the kernel's
/// lifetime, exactly as the `smp.s` trampoline requires. An out-of-memory
/// boot heap parks fail-closed: without stacks no secondary may ever be
/// started.
fn leak_zeroed_secondary_stacks(count: usize) -> &'static [smp::SecondaryStack] {
    // Reserving as `Vec<SecondaryStack>` makes the slots' writeback-granule
    // alignment a property of the allocation itself rather than of a
    // byte-pointer cast, and keeps the out-of-memory path a value.
    let mut stacks: Vec<smp::SecondaryStack> = Vec::new();
    if stacks.try_reserve_exact(count).is_err() {
        serial::beacon("pi-boot: secondary stack allocation FAILED, parking");
        halt_current_cpu()
    }
    let spare = stacks.spare_capacity_mut();
    let spare_bytes = core::mem::size_of_val(spare);
    let spare_start = spare.as_mut_ptr().cast::<u8>();
    // SAFETY: `spare_start`/`spare_bytes` describe exactly `stacks`' own
    // uninitialised capacity, which the reservation above made at least
    // `count` slots long; all-zero is a valid `SecondaryStack` (two zero
    // words and a byte array), so writing zeros over it initialises every
    // slot `set_len` then exposes. Zeroing in place never materialises a
    // 64 KiB value on the boot stack, whose budget that would blow.
    unsafe {
        core::ptr::write_bytes(spare_start, 0, spare_bytes);
        stacks.set_len(count);
    }
    // Leaked, not boxed: the `smp.s` trampoline reads the region for the
    // kernel's lifetime, and leaking the reservation as-is avoids a
    // shrink-to-fit copy of the whole stack pool.
    Vec::leak(stacks)
}

/// Stage the multi-core bring-up: size and publish the secondary stack
/// region, publish the dense-id → affinity table (the identity source a
/// spin-table-released core recovers its dense id from), and install
/// the production secondary entry, so the starts `kernel_main` issues
/// later — PSCI `CPU_ON` or spin-table release — find everything in
/// place.
///
/// `cpu_mpidrs` is the validated dense map from
/// [`crate::cpu_topology::order_cpus`] (entry `i` is dense id `i`'s
/// affinity). Returns `true` when the machine is ready to start
/// secondaries (or is single-CPU, where there is nothing to prepare).
/// Every install is set-once per boot and this is their only production
/// call site, so a refusal is a programmer error; it is reported
/// (`false` → the boot line's `smp_prepared` field) and every later
/// start fails closed and audited rather than releasing a core into a
/// half-published hand-off.
fn prepare_secondary_bringup(cpu_mpidrs: &[u64]) -> bool {
    let cpu_count = cpu_mpidrs.len();
    if cpu_count <= 1 {
        return true;
    }
    let stacks = leak_zeroed_secondary_stacks(cpu_count);
    if smp::register_secondary_stacks(stacks).is_err() {
        return false;
    }
    let mut affinities = Vec::new();
    if affinities.try_reserve_exact(cpu_count).is_err() {
        return false;
    }
    affinities.extend_from_slice(cpu_mpidrs);
    let affinities: &'static [u64] = Box::leak(affinities.into_boxed_slice());
    if smp::register_secondary_affinities(affinities).is_err() {
        return false;
    }
    smp::set_secondary_entry(production_secondary_entry).is_ok()
}

/// Discover each CPU's CoreSight external-debug component base from the
/// firmware tree and install the per-CPU registry the lockup watchdog's
/// cross-core PC sampler reads ([`tairix_arch_aarch64::coresight`]).
///
/// Runs with the dense `cpu_mpidrs` map and the direct map already typed. A
/// discovered base is installed **only** when its window lies in a gigabyte
/// the direct map types as registers, so a read on the lockup path can never
/// fault; a component in an untyped gigabyte — or a tree that describes no
/// debug components
/// (QEMU `virt`, a stock firmware DTB) — installs nothing, and the
/// sampler reports `Unsupported` (fail closed, the buddy detector runs
/// unchanged). Allocation failure or a table with no reachable component is
/// a silent no-op — a diagnostic aid never aborts the boot.
#[cfg(feature = "watchdog-diagnostics")]
fn install_debug_component_bases(fdt: &Fdt<'_>, cpu_mpidrs: &[u64]) {
    use tairix_arch_aarch64::coresight;

    let mut bases = Vec::new();
    if bases.try_reserve_exact(cpu_mpidrs.len()).is_err() {
        return;
    }
    bases.resize(cpu_mpidrs.len(), coresight::NO_BASE);
    fdt::debug_component_bases(fdt, cpu_mpidrs, &mut bases);

    // Only keep a base whose window the direct map already types as
    // registers; a component elsewhere is dropped rather than read through
    // an unmapped (or Normal, cacheable) window.
    for base in &mut bases {
        if *base != coresight::NO_BASE
            && paging::registers_virt(*base as u64, coresight::WINDOW_BYTES).is_none()
        {
            *base = coresight::NO_BASE;
        }
    }

    if bases.iter().any(|&b| b != coresight::NO_BASE) {
        let bases: &'static [usize] = Box::leak(bases.into_boxed_slice());
        coresight::install_debug_bases(bases);
    }
}

/// The entry every started secondary core runs (via the `smp.s`
/// trampoline): per-CPU hardware init, then join the live kernel's
/// dispatch loop.
///
/// Ordering is load-bearing:
///
/// 1. GIC CPU interface + per-CPU preemption/IPI arming — each banked or
///    per-core state that must be programmed on the core that uses it.
/// 2. [`tairix_kernel_core::run_secondary`], which audits the arrival
///    and dispatches until the kernel stops.
///
/// The kernel-core hand-off was published before this core's `CPU_ON`
/// was issued, so a refusal from `run_secondary` is a genuine fault; it
/// is reported on the UART debug line and the core parks fail-closed.
extern "C" fn production_secondary_entry(cpu: u32) -> ! {
    // SAFETY: a per-CPU install on this core, once, its vectors armed by the
    // port's secondary entry and no interrupt source armed here yet; the boot
    // CPU's `gic::init` ran before any `CPU_ON`.
    if let Err(err) = unsafe { gic::init_secondary() } {
        log(
            &crate::console_layout::LOG_SINK,
            &Event {
                level: Level::Warn,
                id: KERNEL_SECONDARY_PARKED,
                message: "aarch64: secondary cpu's GIC interface did not come up; parking",
                fields: &[Field {
                    key: "cause",
                    value: tairix_log::FieldValue::Str(err.as_str()),
                }],
            },
        );
        halt_current_cpu()
    }
    // Per-CPU tickless preemption + IPI arming (the callbacks and the
    // per-CPU backing were installed by the boot CPU before `CPU_ON`).
    crate::aarch64::gic_irq::init_secondary_preemption(cpu);

    // Join the live kernel. Returns only when this core must stop.
    let exit = tairix_kernel_core::run_secondary(cpu);
    log(
        &crate::console_layout::LOG_SINK,
        &Event {
            level: Level::Warn,
            id: KERNEL_SECONDARY_PARKED,
            message: "aarch64: secondary cpu left the dispatch loop; parking",
            fields: &[Field {
                key: "cause",
                value: tairix_log::FieldValue::Str(exit.as_str()),
            }],
        },
    );
    halt_current_cpu()
}

/// Collect the discovered hardware tree — the firmware tree, the
/// bootstrap-floor virtio-MMIO devices, and the boot display — and hand it to
/// the boot record ([`crate::unlock_service::record_boot`]), which resolves
/// the root block binding from it and moves it into the live inventory.
///
/// A null or unreadable tree, or a malformed walk, records nothing: the
/// root stays unbound and the boot carries on.
///
/// `video` carries the scan-out facts of a surface the firmware lit, if any;
/// where the console is shown is decided from it and the display engine the
/// tree enables, and answered (`plans/DISPLAY.md` D7d). A GICv3's
/// redistributor regions, `gic_redistributor_stride` apart, say whether the
/// boot CPU can take the LPIs a PCI function's messages would raise.
fn audit_root_storage_binding(
    tree: u64,
    video: Option<video::DiscoveredVideo>,
    gic_redistributors: &[gicv3::RedistributorRegion],
    gic_redistributor_stride: Option<gicv3::RedistributorStride>,
    log_sink: &'static (dyn Sink + Sync),
) -> crate::boot_display::ConsolePlacement {
    if tree == 0 {
        return crate::boot_display::ConsolePlacement::Nowhere;
    }
    // SAFETY: `tree` is the device tree mapped read only for the kernel's
    // life; `Fdt::from_ptr` checks its magic and bounds it by its own
    // `totalsize` before any further read.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(tree as *const u8) }) else {
        return crate::boot_display::ConsolePlacement::Nowhere;
    };
    // The validated blob's own length, captured before the walk consumes
    // the reader, so the virtio-MMIO probe below can reborrow the same
    // firmware bytes the bus builder needs.
    let total = fdt.total_size();
    let mut sink = crate::boot_hwtree::CollectingHwNodeSink::new();
    if platform::FdtDiscovery::new(fdt)
        .discover(&mut sink)
        .is_err()
    {
        // A malformed tree is not fatal: leave the root unbound — the mount
        // path fails closed without a binding.
        return crate::boot_display::ConsolePlacement::Nowhere;
    }

    // Bootstrap-floor virtio-MMIO bus enumeration: the raw `virtio,mmio` nodes the discovery walk emitted carry
    // only their `compatible` string, which binds no block driver — the
    // virtio-blk bind key is the device id read from the transport. Probe
    // each slot's `DeviceID` through the MMIO bus driver and emit a probed
    // virtio-block child node into the same buffered tree so the gate can
    // bind the root *and* the kthread's autoload sees a faithful tree. A
    // tree that describes no `virtio,mmio` node makes
    // `virtio_mmio_bus_from_dtb` return `NotFound`, so this is a no-op there
    // — it is the QEMU `virt`-board path, additive and metal-neutral.
    // SAFETY: `tree`/`total` bound the blob `Fdt::from_ptr` validated above,
    // mapped read only and immutable for the kernel's life; the virtio-MMIO
    // aperture it describes is reached where the direct map types it as
    // registers, which the probe alone reads (side-effect-free `DeviceID`
    // registers).
    let dtb_bytes = unsafe { core::slice::from_raw_parts(tree as *const u8, total) };
    let probe = unsafe {
        tairix_drv_bus_mmio::virtio_mmio_bus_from_dtb(dtb_bytes, |base, len| {
            paging::registers_virt(base, len).map(|at| at as *const u32)
        })
    };
    if let (Ok(bus), Ok(slots)) = (probe, Fdt::new(dtb_bytes)) {
        // Read before the probes add nodes of their own.
        let dma = crate::iommu_fdt::SlotDma::read(
            &slots,
            sink.nodes(),
            <tairix_arch_aarch64::platform::Aarch64Fdt as tairix_arch_api::fdtwalk::FdtPlatform>::DEFAULT_DMA_COHERENCE,
        );
        // A bus enumeration error (an over-full or malformed bus) leaves the
        // root unbound rather than aborting the boot.
        let _ = crate::hwdiscovery::observe_virtio_mmio_block_devices(&bus, &dma, &mut sink);
        // Each interrupt-driven device is emitted with its slot's line, as its
        // node's `interrupts` decodes; a slot whose line cannot be resolved
        // is left undiscovered.
        let slot_irq = |slot_base| crate::aarch64::root_unlock::device_spi(&slots, slot_base);
        let _ = crate::hwdiscovery::observe_virtio_mmio_input_devices(
            &bus, &slot_irq, &dma, &mut sink, log_sink,
        );
        let _ = crate::hwdiscovery::observe_virtio_mmio_network_devices(
            &bus, &slot_irq, &dma, &mut sink, log_sink,
        );
        let _ = crate::hwdiscovery::observe_virtio_mmio_audio_devices(
            &bus, &slot_irq, &dma, &mut sink, log_sink,
        );
        let _ = crate::hwdiscovery::observe_virtio_mmio_display_devices(
            &bus, &slot_irq, &dma, &mut sink, log_sink,
        );
    }

    // Every generic ECAM host the tree describes becomes the kernel's own,
    // its functions raising LPIs where an ITS can take their messages.
    // SAFETY: as above — `tree` bounds the blob validated at boot, mapped
    // read only and immutable for the kernel's life.
    if let Ok(fdt) = unsafe { Fdt::from_ptr(tree as *const u8) } {
        let mut lpis = crate::aarch64_messages::discover(
            &fdt,
            gic_redistributors,
            gic_redistributor_stride,
            crate::aarch64_messages::first_lpi_line(
                crate::aarch64::gic_irq::msi_mux().map(tairix_kernel_core::MsiMuxLines::lines),
            ),
        );
        let intx = IntxOnGic(gic::find_gic(&fdt).and_then(|gic| gic.phandle));
        crate::pci_fdt::seed(&fdt, &PciPort, &intx, &mut lpis, &mut sink, log_sink);
        crate::aarch64_messages::publish(lpis.into_routes());
    }

    // The console is shown on a display engine the tree enables or a virtio
    // GPU, either of which takes the screen over, else on the surface the
    // firmware lit.
    // SAFETY: as above.
    let engine = unsafe { Fdt::from_ptr(tree as *const u8) }
        .ok()
        .and_then(|fdt| platform::display_engine(&fdt))
        .or_else(|| crate::boot_display::virtio_gpu(&sink));
    let scanout = video.map(|video| crate::boot_display::BootScanout {
        base: video.fb_base,
        width_px: video.width_px,
        height_px: video.height_px,
        stride_bytes: video.stride_bytes,
        format: video.format,
        memory: video.memory,
    });
    let placement = crate::boot_display::place_console(&mut sink, engine, scanout.as_ref());

    crate::unlock_service::record_boot(tree, sink.into_vec(), log_sink);
    placement
}

/// Put the framebuffer console where discovery `placement` says: kept for a
/// display engine that will host it, with no surface to paint until then,
/// where `attached` found none the firmware lit; retired from the firmware's
/// `video` surface where an engine displaces it and can never host it, so the
/// UART stays the console rather than a login on a screen nobody sees.
fn place_video_console(
    placement: crate::boot_display::ConsolePlacement,
    attached: bool,
    video: Option<video::DiscoveredVideo>,
) {
    use crate::boot_display::ConsolePlacement;
    use crate::console_layout::CONSOLE;
    match (placement, video) {
        (ConsolePlacement::Hosted, _) if !attached => {
            let _ = CONSOLE.attach(Some(tairix_fbcon::Geometry::UNHOSTED));
        }
        (ConsolePlacement::Displaced, Some(video)) if attached => {
            let _ = CONSOLE.retire(video.fb_base);
        }
        _ => {}
    }
}

/// A kernel mapping of the device registers at `[base, base + len)`: a
/// window wholly inside the direct map's register gigabytes, at its
/// direct-map address. Anything else fails closed: no other mapping of a
/// register window is uncached.
pub(crate) fn device_registers(base: u64, len: usize) -> Option<core::ptr::NonNull<u8>> {
    let virt = paging::registers_virt(base, u64::try_from(len).ok()?)?;
    core::ptr::NonNull::new(core::ptr::with_exposed_provenance_mut(
        usize::try_from(virt).ok()?,
    ))
}

/// The physical map register windows are reached through: the direct map's
/// register gigabytes, where the board's discovered MMIO lives.
///
/// Those are sparse, so this is no general physical map: RAM is reached
/// through [`SPAWN_TABLE_PHYSMAP`](crate::aarch64::spawn_producer::SPAWN_TABLE_PHYSMAP),
/// and a window not wholly inside a register gigabyte fails closed rather
/// than aliasing memory the direct map holds cacheable.
pub struct DeviceWindows;

impl PhysMap for DeviceWindows {
    fn translate(&self, phys: PhysAddr, len: usize) -> Option<core::ptr::NonNull<u8>> {
        device_registers(phys.as_u64(), len)
    }

    /// Device memory is never cached, so there is no alias to clean.
    fn clean_invalidate(&self, _phys: PhysAddr, _len: usize) {}

    /// Register windows are never executed.
    fn sync_instruction_cache(&self, _phys: PhysAddr, _len: usize) {}

    fn fence_instruction_fetch(&self) -> bool {
        true
    }
}

/// How a generic ECAM host reaches this port: its configuration region
/// through the kernel's Device windows, its INTx on the GIC.
struct PciPort;

impl crate::pci_fdt::FdtPort for PciPort {
    fn dma_convention(&self) -> tairix_abi::DmaCoherence {
        <tairix_arch_aarch64::platform::Aarch64Fdt as tairix_arch_api::fdtwalk::FdtPlatform>::DEFAULT_DMA_COHERENCE
    }

    fn registers(&self, base: u64, len: usize) -> Option<core::ptr::NonNull<u8>> {
        device_registers(base, len)
    }

    fn reach(&self) -> u64 {
        paging::PHYSMAP_REACH
    }
}

/// A function's INTx on the GIC, by its phandle read once from the tree.
struct IntxOnGic(Option<u32>);

impl crate::pci_fdt::IntxLines for IntxOnGic {
    fn line(&self, spec: &tairix_fdt::pci::InterruptSpec) -> Option<u32> {
        if self.0 != Some(spec.parent) {
            return None;
        }
        match spec.cells() {
            &[kind, number, _] => fdt::gic_intid_from_cells(kind, number),
            _ => None,
        }
    }
}

/// The two memory figures the hand-off carries, which discovery produces
/// together and only [`BootInfo`] consumes: the physical map the frame
/// allocator is built from, and the platform's installed total *before* the
/// identity map's Device clip drops the bytes it cannot reach.
struct BootMemory {
    map: tairix_kernel_mem::BootMemoryMap,
    installed_bytes: u64,
}

/// Assemble the validated [`BootInfo`] hand-off and enter
/// [`tairix_kernel_core::kernel_main`].
///
/// Installs the production `svc` dispatch callback before user space can
/// be entered (the `kernel_core` `Syscall` phase publishes the resident
/// hook into [`DISPATCH_SLOT`]), wraps the validated [`Aarch64Arch`] in
/// the local [`Aarch64BinArch`] `KernelArch`, and installs the discovered
/// console list: with the framebuffer boot console active the video
/// console is the only console and the UART stays the session-free debug
/// log line (`plans/PI.md` P11); otherwise the UART is the only console.
/// A hand-off that `BootInfo::validate` rejects parks fail-closed rather
/// than entering the core.
fn enter_kernel_core(
    arch: Aarch64BinArch,
    memory: BootMemory,
    heap: &'static tairix_kalloc::FreeListAllocator,
    log_sink: &'static (dyn Sink + Sync),
    audit_sink: &'static (dyn Sink + Sync),
    log_level: Level,
    hw_tree: &'static (dyn tairix_kernel_core::HwTreeSource + 'static),
) -> ! {
    // The arch port's `svc` trampoline fail-closes if it fires before a
    // callback is installed, so install it before any user thread runs.
    // No user space exists yet at P6c-2; pinning it here keeps the
    // ordering identical to the x86_64 boot path.
    syscall_entry::set_dispatch_callback(production_dispatch);

    // Arm the task-latency watchdog beside the dispatcher it observes: an
    // interactive surface that declares a frame budget then gets an overrun
    // report naming the blocking call and the user code that stalled. The
    // layout is this port's own frame-pointer convention, the same constant
    // its fault-path backtrace uses. Debug image only; a shippable image
    // installs no observer and the entry hook costs one relaxed load.
    #[cfg(feature = "watchdog-diagnostics")]
    tairix_kernel_core::latency::install(tairix_arch_aarch64::backtrace::Backtracer::LAYOUT);
    // Demand-paged file mappings resolve their EL0 data aborts through the
    // same resident hook; install the resolver beside the dispatch callback
    // so both are in place before user space exists. This single-entry boot
    // path installs exactly once; a second publish would be a programmer
    // error, so it parks fail-closed rather than running with an
    // unpredictable fault path.
    if tairix_arch_api::fault::set_user_fault_resolver(production_user_fault).is_err() {
        tairix_arch_aarch64::kernel_arch::halt_current_cpu();
    }
    // Beside the resolver, install the terminator the trap handler uses for
    // an EL0 exception it cannot resolve (an illegal instruction, an
    // alignment fault): it kills the offending task and keeps the CPU alive,
    // so one task's bad instruction can never park a core. Installed once,
    // before user space; a second publish is a programmer error that parks
    // fail-closed rather than running with an unpredictable fault path.
    if tairix_arch_api::fault::set_user_fault_terminator(production_user_fault_terminate).is_err() {
        tairix_arch_aarch64::kernel_arch::halt_current_cpu();
    }

    // The discovered dense CPU count sizes the scheduler's run queues
    // and names how many cores `kernel_main`'s SMP phase brings online.
    let cpu_count = arch.arch().cpu_count();
    // Recover the firmware power-control conduit the boot path discovered
    // from the `/psci` node (the same method the secondary-core bring-up
    // uses) so the Supervisor's `reboot`/`poweroff` can drive PSCI
    // `SYSTEM_RESET` / `SYSTEM_OFF` through it. A tree with no `/psci` node
    // (spin-table bring-up) leaves it `None`, so both fail safe (unsupported).
    let psci_method = match arch.arch().secondary_start() {
        Some(SecondaryStart::Psci(method)) => Some(method),
        _ => None,
    };
    let arch = Arc::new(arch.with_psci_method(psci_method));
    // Publish the arch handle for the panic-handler bridge before it is
    // moved into `BootInfo` (a panic after this point carries registers +
    // a backtrace; before it, the pre-init serial path runs).
    // SAFETY: `arch` is moved into `BootInfo` immediately below (which
    // `kernel_main` consumes and stores); `Arc::as_ptr` is stable for the
    // lifetime of any clone of the `Arc`.
    unsafe {
        crate::aarch64::panic_ctx::publish_arch(Arc::as_ptr(&arch));
    }
    // One decision for the console list and the seat registry, so the seat's
    // text sink, the console whose display surface its lease hands over, and
    // the console a descriptor's index names cannot disagree.
    let (consoles, seat_registry) = console_layout();
    let boot_info = BootInfo::new(
        BOOT_CPU,
        cpu_count,
        "",
        memory.map,
        SchedulerConfig::defaults_for(cpu_count),
        arch,
        log_sink,
        audit_sink,
        log_level,
        &DISPATCH_SLOT,
        heap,
    )
    // Install the discovered console list (`plans/PI.md` P11): when the
    // P7b framebuffer boot console came up, the display (with its
    // keyboard input seam) is the only console — the UART then carries
    // the debug log alone, with no session that would draw over it; with
    // no display, the discovered UART is the only console. Each entry is
    // a `stream_write`/`stream_read` backing pair.
    .with_consoles(consoles)
    // Record the firmware-discovered installed-RAM total so the core mints
    // the `boot_facts_get` machine summary from it.
    .with_installed_memory(memory.installed_bytes)
    // Install the kernel seat registry (`plans/DISPLAY.md` D2 — input
    // follows the surface owner): its text sink is that same console's
    // keyboard queue, so an injected key press reaches the login by
    // default, and the window manager's owner-checked `display_acquire`
    // later routes whole records to the desktop keyboard channel instead.
    // Acquiring the seat also hands the console's display surface to the
    // session, and every way the lease can end gives it back (D8).
    .with_seat_registry(seat_registry)
    // Install the PID 1 spawn seam (`plans/PI.md` P6c-3): once every init
    // phase has succeeded and `kernel_main` emits `BootCompleted`, the core
    // invokes it to build `init`'s EL0 image and drop into user mode.
    .with_init(&crate::aarch64::init_spawn::AARCH64_INIT_SPAWN)
    // Install the runtime `spawn` producer + embedded-program registry
    // (`plans/SPAWN.md` SP3b): the `spawn` syscall resolves a path against
    // the registry and drives the producer to build a fresh, isolated child
    // address space, so PID 1 `init` can launch the user's session.
    .with_spawn(
        &crate::spawn_layout::PROGRAM_REGISTRY,
        &crate::aarch64::spawn_producer::AARCH64_PROCESS_SPAWN,
    )
    // Install the on-disk application store (`plans/APPS.md` deliverable 8):
    // this port embeds no program rows, so every command app and service is
    // spawned from its verified `/System` store bundle. The storage bring-up
    // resolves the store's readiness latch on every outcome (mount installed
    // or given up), so a spawn racing the mount parks and always wakes.
    .with_app_store(&crate::app_store::APP_STORE)
    // Hand the syscall dispatch hook the shared set-once credential cell
    // (`plans/PI.md` P11 Chunk B-2): `users_db_read` reads it on every
    // call, and the in-kernel root-unlock kthread publishes the mounted
    // root volume's database into the *same* cell once the root is mounted.
    // Until that install the cell
    // fails every read closed, identical to the previous `NULL_USERS_DB`
    // default — so login refuses every attempt until a root is mounted, and the metal-confirmed boot is unaffected.
    .with_users_db(&crate::root_mount::LATE_USERS_DB)
    .with_groups_db(&crate::root_mount::LATE_GROUPS_DB)
    .with_users_admin(&crate::root_mount::LATE_USERS_ADMIN)
    // Serve the discovered hardware tree through the injected `hw_tree`
    // source: the `hw_tree_read` / `hw_tree_wait` syscalls read the one
    // authoritative `HW_TREE` the boot record seeds and user-space bus
    // drivers publish into (production installs `HW_TREE_SOURCE`), so the
    // user-space device manager observes the same inventory the kernel
    // discovered (Design D).
    .with_hw_tree(hw_tree)
    // Serve the `fs_*` syscalls through the production filesystem service:
    // it routes each operation through the secured
    // VFS against the late-installed read-only `/System` mount and resolves
    // caller groups against the late-installed identity table. Both cells
    // fail closed (`NotImplemented`) until the disk-owning task publishes the
    // `/System` window (`crate::system_mount::install_system_mount`) and the
    // root unlock publishes the identity table, so wiring the hook
    // here changes no boot behaviour until those installs land.
    .with_filesystem(&crate::system_mount::FS_SERVICE)
    // Resolve `id::<volume-id>/…` paths against the volume forest the
    // mount/unlock tasks publish each mounted volume's stable identity
    // into (`plans/DEVICES.md` D3a). Until a volume is published every
    // `id::` path fails closed `NotFound`, so wiring the hook here changes
    // no boot behaviour until those installs land.
    .with_volumes(&crate::system_mount::VOLUME_FOREST)
    // Delegate runtime volume attach/detach (`plans/DEVICES.md` D3b) to
    // the production service; it fails closed `NotImplemented` until the
    // mount task wires its audit sink and pressure gauge, so this changes
    // no boot behaviour until that install lands.
    .with_volume_service(&crate::volume_service::VOLUME_SERVICE)
    // Resolve a spawn-as-user switch against the
    // same set-once identity cell the filesystem service resolves caller
    // groups against and the root-unlock kthread publishes the on-disk
    // accounts into. Until that install a switch fails closed; the default
    // `spawn` (inherit) never consults it, so wiring the hook here changes no
    // boot behaviour until the unlock lands.
    .with_spawn_identity(&crate::root_mount::LATE_IDENTITY);
    if boot_info.validate().is_err() {
        halt_current_cpu()
    }
    kernel_main(boot_info)
}

/// What device bring-up resolved from the firmware device tree.
struct EarlyDiscovered {
    /// A recognised console UART was found.
    console: bool,
    /// A GIC was found.
    gic: bool,
    /// The framebuffer boot console came up: a firmware mailbox was
    /// found, a display is attached, and the scan-out surface was
    /// allocated — console output now defaults to the screen, with the
    /// UART as the fallback (`plans/PI.md` P7b).
    video: Option<video::DiscoveredVideo>,
    /// The platform PCIe root complex's windows, when the tree describes the
    /// one the port knows (`plans/PI.md` P10). `None` on a board with none
    /// (the QEMU `virt` shape).
    pcie: Option<platform::PcieDiscovery>,
    /// The rate in Hz the firmware was asked to run the ARM cores at, or `0`
    /// on a board with no firmware clock (the QEMU `virt` shape) or where the
    /// request failed. Recorded so the boot log can state the speed the rest
    /// of boot ran at rather than leaving it to be inferred.
    cpu_clock_hz: u64,
}

/// Record `video`'s surface as the console's; `false` for a mode no glyph
/// fits, leaving the UART the console.
fn publish_boot_surface(video: &video::DiscoveredVideo) -> bool {
    let Some(base) = video.base() else {
        return false;
    };
    // SAFETY: the boot CPU, before anything else reaches the console;
    // discovery proved `[fb_base, fb_base + fb_len_bytes)` holds the mode and
    // is RAM owned for scan-out (the kernel's ramfb surface, or the
    // firmware's), which the direct map covers at `base`.
    unsafe { crate::console_layout::CONSOLE.publish(base, video.surface()) }
}

/// Bring up the console UART and the framebuffer boot console, raise the
/// cores to their full rate, and find the PCIe root complex, on the board
/// [`type_direct_map`] typed. A null pointer, an unreadable/invalid blob, or
/// a tree missing a fact leaves the corresponding pre-discovery default
/// untouched — for video, the UART console (fail closed).
fn configure_mmio_from_dtb(tree: u64) -> EarlyDiscovered {
    let mut out = EarlyDiscovered {
        console: false,
        gic: false,
        video: None,
        pcie: None,
        cpu_clock_hz: 0,
    };
    if tree == 0 {
        return out;
    }
    // SAFETY: `tree` is the device tree mapped read only for the kernel's
    // life; `Fdt::from_ptr` checks its magic and bounds it by its own
    // `totalsize` before any further read.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(tree as *const u8) }) else {
        return out;
    };
    out.console = console::find_console(&fdt).is_some();
    // Bring the discovered console's line up before the first log byte:
    // on real silicon a UART can stay silent until its pins are muxed to it
    // and its line registers are programmed — QEMU's powered-up PL011 masks
    // the omission (`uart_init`).
    uart_init::init_from_fdt(&fdt);
    out.gic = gic::find_gic(&fdt).is_some();
    // Ask the firmware for full speed before anything else runs. Where the
    // ARM clock is the firmware's, it leaves it at `arm_freq_min` — 600 MHz
    // on a board rated at 1.5 GHz — until an OS driver asks otherwise, so
    // mounting the root volume, unlocking it, and reaching a login would all
    // run at 40% of the machine's speed. The frequency driver `devmgr`
    // autoloads takes over from here; this is the floor beneath it, and it
    // fails closed to whatever rate the firmware had chosen.
    match firmware::find_mailbox(&fdt) {
        Some(mailbox) => {
            let _ = firmware::with_transport(mailbox, |transport| {
                out.cpu_clock_hz = firmware::raise_over(transport).map_or(0, u64::from);
                out.video = video::configure(&fdt, Some((mailbox, transport)));
            });
        }
        None => out.video = video::configure(&fdt, None),
    }
    out.video = out.video.filter(publish_boot_surface);
    out.pcie = platform::pcie_bringup(&fdt);
    out
}

/// The gigapages every generic ECAM host's configuration region lies in,
/// however many hosts the tree describes.
fn pci_config_gigapages(fdt: &Fdt<'_>) -> [u64; GIGAPAGE_MASK_WORDS] {
    let mut mask = [0; GIGAPAGE_MASK_WORDS];
    tairix_fdt::pci::each_pci_host(fdt, |host| {
        for (word, host) in mask
            .iter_mut()
            .zip(gigapage_mask_from_extents(&[host.ecam]))
        {
            *word |= host;
        }
    });
    mask
}

/// What the boot resolved from the firmware device tree beyond its devices.
struct Discovered {
    /// The generic-timer counter frequency (Hz) to seed the handle and
    /// the P4 live timer with: the `/timer` `clock-frequency` override
    /// when the tree declares one, else the `CNTFRQ_EL0` register value.
    timer_hz: u64,
    /// `true` when `timer_hz` came from the device-tree override rather
    /// than the `CNTFRQ_EL0` register.
    timer_hz_from_tree: bool,
    /// The PSCI conduit (`hvc`/`smc`) the `/psci` node declares, used to
    /// issue `CPU_ON` for SMP bring-up (`plans/PI.md` P5). `None` when the
    /// tree declares no PSCI node; bring-up then rides the spin-table
    /// release when the cpu nodes declare one, else fails closed.
    psci_method: Option<fdt::PsciMethod>,
    /// Every `/cpus/cpu@*` `reg` affinity (`MPIDR_EL1` `Aff0`–`Aff2`)
    /// the firmware tree declares, in tree order — the CPU inventory
    /// [`crate::cpu_topology::order_cpus`] validates into the dense map
    /// every per-CPU structure is sized from. Empty when the tree
    /// declares none or the walk fails (the boot then falls back closed
    /// to a single-CPU map).
    cpu_mpidrs: Vec<u64>,
    /// `(affinity, cpu-release-addr)` for every cpu node that declares
    /// the `spin-table` enable method, in tree order — aligned to the dense
    /// map by [`crate::cpu_topology::align_release_addrs`] and used for
    /// bring-up only when the tree declares no PSCI node. Empty when none
    /// are declared or the walk fails (fail closed).
    cpu_spin_releases: Vec<(u64, u64)>,
    /// A GICv3's redistributor regions, in tree order; empty on a GICv2.
    gic_redistributors: Vec<gicv3::RedistributorRegion>,
    /// The stride between a GICv3's redistributors, where the tree names one.
    gic_redistributor_stride: Option<gicv3::RedistributorStride>,
}

/// Discover the timer rate, the PSCI conduit and the CPUs from the device
/// tree at `tree`.
///
/// A null pointer, an unreadable/invalid blob, or a tree missing a fact
/// leaves the corresponding pre-discovery `virt` default untouched (fail
/// closed).
fn configure_from_dtb(tree: u64) -> Discovered {
    let mut out = Discovered {
        // With no usable tree the register is the only counter-rate
        // source; P4's tree override (if any) overwrites this below.
        timer_hz: read_cntfrq(),
        timer_hz_from_tree: false,
        psci_method: None,
        cpu_mpidrs: Vec::new(),
        cpu_spin_releases: Vec::new(),
        gic_redistributors: Vec::new(),
        gic_redistributor_stride: None,
    };
    if tree == 0 {
        return out;
    }
    // SAFETY: `tree` is the device tree mapped read only for the kernel's
    // life; `Fdt::from_ptr` checks its magic and bounds it by its own
    // `totalsize` before any further read.
    let Ok(fdt) = (unsafe { Fdt::from_ptr(tree as *const u8) }) else {
        return out;
    };
    // P4: prefer the board's `/timer` `clock-frequency` over the
    // `CNTFRQ_EL0` register, so the crystal the firmware tree declares is
    // honoured (no `cfg(board)` fork).
    out.timer_hz_from_tree = fdt::timer_clock_frequency(&fdt).is_some_and(|hz| hz != 0);
    out.timer_hz = timer_frequency_hz(&fdt);
    // P5: discover the PSCI conduit (`hvc`/`smc`) the firmware tree
    // declares, so secondary-core bring-up issues `CPU_ON` over the
    // board's conduit rather than an assumed one.
    out.psci_method = fdt::psci_method(&fdt);
    // Collect every `/cpus/cpu@*` affinity so the bring-up starts the
    // cores the board *declares*, never an assumed count — along with each
    // node's spin-table release word, the PSCI-less start channel. A
    // malformed walk discards the partial lists — the boot then sizes for
    // the one running core rather than trusting a truncated inventory (fail
    // closed).
    let mut cpus = Vec::new();
    let mut spin_releases = Vec::new();
    if fdt
        .each_cpu(|cpu| {
            let affinity = cpu.reg & smp::MPIDR_AFFINITY_MASK;
            cpus.push(affinity);
            if let Some(addr) = cpu.spin_table_release {
                spin_releases.push((affinity, addr));
            }
        })
        .is_err()
    {
        cpus.clear();
        spin_releases.clear();
    }
    out.cpu_mpidrs = cpus;
    out.cpu_spin_releases = spin_releases;
    let mut regions = Vec::new();
    if let Some(stride) = gic::redistributor_regions(&fdt, |region| regions.push(region)) {
        out.gic_redistributors = regions;
        out.gic_redistributor_stride = stride;
    }
    // Record the console UART's receive-interrupt line so the root-unlock
    // console handoff can switch `login`'s input from polled to
    // interrupt-driven (`crate::aarch64::gic_irq::enable_uart_console_irq`).
    // Unconditionally, so the no-disk path (which never runs the unlock
    // kthread) still gets it. A tree without a
    // representable console interrupt leaves `login` on the polled path (fail
    // closed — `login` then keeps re-polling, never errors).
    if let Some(intid) =
        tairix_arch_aarch64::console::find_console(&fdt).and_then(|console| console.intid)
    {
        crate::aarch64::gic_irq::set_uart_console_intid(intid);
    }
    // The chained message multiplexer the tree describes, if any, backs
    // `msi_alloc`; with none, `msi_alloc` fails closed (the QEMU `virt`
    // shape).
    if let Some(mux) = tairix_arch_aarch64::msimux::configure_from_fdt(&fdt) {
        crate::aarch64::gic_irq::install_msi_mux(mux);
    }
    out
}
