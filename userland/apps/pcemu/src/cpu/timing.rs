/// The family's table.
#[must_use]
pub const fn costs(family: Family) -> &'static Costs {
    match family {
        Family::Intel8086 => &I8086,
        Family::Intel80186 => &I80186,
        Family::Nec => &NEC,
    }
}

/// Effective-address calculation: the 8086 family's separate charge (a
/// segment override is its prefix's own two cycles); folded into the others'
/// counts.
#[must_use]
pub const fn ea(family: Family, mem: Mem) -> u32 {
    if !matches!(family, Family::Intel8086) {
        return 0;
    }
    let base = match mem.base {
        Base::Absolute => 6,
        Base::Si | Base::Di | Base::Bx | Base::Bp => 5,
        Base::BxSi | Base::BpDi => 7,
        Base::BxDi | Base::BpSi => 8,
    };
    if mem.displaced {
        base + 4
    } else {
        base
    }
}

/// Cycles for entering the single-step trap.
#[must_use]
pub const fn trap_entry(model: CpuModel) -> u32 {
    costs(model.family()).trap as u32
}

/// Cycles for entering NMI.
#[must_use]
pub const fn nmi_entry(model: CpuModel) -> u32 {
    costs(model.family()).nmi as u32
}

/// Cycles for an INTR acknowledge and entry.
#[must_use]
pub const fn intr_entry(model: CpuModel) -> u32 {
    costs(model.family()).intr as u32
}
