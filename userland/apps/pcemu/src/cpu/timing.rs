//! Instruction timing: the manufacturers' published cycle counts, calibrated
//! against hardware-captured bus traces where they exist.
//!
//! Counts are for the 16-bit-bus part with aligned operands. Each word
//! transfer an 8-bit bus or an odd address splits in two costs four more
//! cycles, added where the transfer happens, so the 8088, 80188 and V20 need
//! no tables of their own. The 8086 family charges effective-address
//! calculation separately; the 80186 and the V-series fold it in.

