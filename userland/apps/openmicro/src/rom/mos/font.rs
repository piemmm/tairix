/// A glyph row's byte: its leftmost pixel the top bit.
fn row_byte(row: &str) -> u8 {
    row.bytes()
        .fold(0, |byte, pixel| (byte << 1) | u8::from(pixel == b'#'))
}

pub fn emit(a: &mut Asm) {
    a.org(FONT);
    a.here("font");
    for glyph in &GLYPHS {
        for row in glyph {
            a.byte(row_byte(row));
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_is_eight_rows_of_eight_pixels() {
        for (code, glyph) in (32..).zip(&GLYPHS) {
            for row in glyph {
                assert_eq!(row.len(), 8, "character {code}");
                assert!(
                    row.bytes().all(|pixel| matches!(pixel, b'#' | b'.')),
                    "character {code}"
                );
            }
        }
        assert_eq!(row_byte("#......."), 0x80);
        assert_eq!(row_byte(".......#"), 0x01);
    }
}
