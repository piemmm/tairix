#[test]
fn the_editor_does_what_the_original_did() {
    for case in CASES {
        let mut machine = settled(Standard::Pal, &print_then_input(case.printed));
        type_keys(&mut machine, case.keys);
        let seen = state(&machine);
        let mut screen = [0x20u8; 1000];
        for &(row, codes) in case.rows {
            screen[row * 40..row * 40 + codes.len()].copy_from_slice(codes);
        }
        assert_eq!(seen.screen[..], screen[..], "{}: the screen", case.name);
        assert_eq!(
            seen.continuations, case.continuations,
            "{}: the lines",
            case.name
        );
        assert_eq!(seen.cursor, case.cursor, "{}: the cursor", case.name);
        assert_eq!(
            seen.line_end, case.line_end,
            "{}: the line's end",
            case.name
        );
        assert_eq!(seen.input, case.input, "{}: what CHRIN returned", case.name);
        assert_eq!(seen.modes, case.modes, "{}: the modes", case.name);
    }
}
