//! `HELP`'s topics, in TAIRiX Bridge's own words: the keywords BASIC V's
//! table lists, in its order, then the print format and the assembler.

/// A keyword `HELP .` lists, and what `HELP` says of it, a line a string.
pub(crate) struct Topic {
    pub(crate) name: &'static str,
    pub(crate) text: &'static [&'static str],
}

const fn topic(name: &'static str, text: &'static [&'static str]) -> Topic {
    Topic { name, text }
}

